#!/usr/bin/env bash
#
# Учение по восстановлению из УДАЛЁННОГО хранилища.
#
# Копия становится бэкапом только в тот момент, когда её однажды восстановили.
# До этого она — файл, о котором мы верим, что он подойдёт.
#
# Этот скрипт скачивает снимок из офсайт-хранилища (не из локального каталога),
# проверяет данные и — если не отключено — поднимает на восстановленной базе
# приложение через deploy/restore_test.sh. Боевую базу и боевой сервис не
# трогает: восстановленная копия кладётся только в новый файл и только если
# путь указан явно вторым аргументом.
#
# Источник идеи — ветка Codex codex/offsite-backup-restore: `restic check
# --read-data` (проверять не только метаданные, но и сами блоки), отказ писать
# поверх боевой базы, отдельный снимок по имени. Реализация своя.
#
# Что исправлено относительно источника: там учение проверяло, что четыре
# ключевые таблицы СУЩЕСТВУЮТ. Пустая, но структурно целая база это условие
# выполняет — и объявляется годной копией. Здесь проверяются строки.
#
# Второе исправление — по внешнему ревью 23.08. Учение доказывало «данные
# доехали» и «приложение стартует», но обе проверки проходит и база, все токены
# МойСклада в которой нечитаемы: они зашифрованы ключом, выведенным из
# OBOROT_SECRET, а секрета в бэкапе нет и быть не должно. Восстановление без
# секрета — это система, которая поднялась, показывает старые цифры и не может
# ни синхронизироваться, ни отправить заказ. Поэтому учение обязано
# расшифровать настоящий токен ОТДЕЛЬНОЙ офсайт-копией секрета
# (OBOROT_RECOVERY_SECRET_FILE), и без неё оно не начинается вовсе.
#
# Третье исправление — по повторному ревью 23.08. «Отдельная копия» и файл
# `/opt/oborot/recovery-secret` на том же диске, что и база, — это разные вещи,
# а в документации стояли как одно. Теперь копия обязана лежать на ДРУГОЙ
# файловой системе, чем боевая база: подключённый на чтение каталог с другой
# машины или временная выгрузка из внешнего secret store. Что это необходимое
# условие, а не доказательство отдельного домена отказа, сказано и здесь, и в
# отметке об учении (domain=), и в OPS-4.
#
# Запуск:   bash deploy/offsite_restore_drill.sh [snapshot] [куда-положить.db]
# Отключить подъём приложения:  OBOROT_DRILL_BOOT_APP=0
# Стенд без монтирования:       OBOROT_DRILL_ALLOW_LOCAL_SECRET=1 (domain=не-проверен)
set -euo pipefail
umask 077

HERE="$(cd "$(dirname "$0")" && pwd)"

CONFIG_FILE="${OBOROT_BACKUP_ENV_FILE:-/opt/oborot/backup.env}"
if [ -f "$CONFIG_FILE" ]; then
  set -a
  # shellcheck disable=SC1090
  . "$CONFIG_FILE"
  set +a
fi

DB="${OBOROT_DB:-/opt/oborot/data/oborot.db}"
STATE_DIR="${OBOROT_BACKUP_STATE_DIR:-/opt/oborot/backup-state}"
RESTIC="${OBOROT_RESTIC_BIN:-restic}"
HOST_TAG="${RESTIC_HOST:-oborot-production}"
SNAPSHOT="${1:-latest}"
OUTPUT="${2:-}"
BOOT_APP="${OBOROT_DRILL_BOOT_APP:-1}"
FULL_CHECK="${OBOROT_DRILL_FULL_CHECK:-1}"
VENV="${OBOROT_VENV:-/opt/oborot/venv}"
RECOVERY_SECRET_FILE="${OBOROT_RECOVERY_SECRET_FILE:-}"
ALLOW_LOCAL_SECRET="${OBOROT_DRILL_ALLOW_LOCAL_SECRET:-0}"

die() { echo "УЧЕНИЕ ПРОВАЛЕНО: $*" >&2; exit 1; }

# Номер устройства файловой системы, на которой лежит путь. GNU и BSD печатают
# его разными ключами, поэтому обе формы.
fs_device() {
  stat -c '%d' "$1" 2>/dev/null || stat -f '%d' "$1" 2>/dev/null || return 1
}

for c in sqlite3 flock mktemp gzip stat; do
  command -v "$c" >/dev/null 2>&1 || die "нет команды $c"
done
command -v "$RESTIC" >/dev/null 2>&1 || die "нет restic ($RESTIC)"
[ -n "${RESTIC_REPOSITORY:-}" ] || die "не задан RESTIC_REPOSITORY"
[ -n "${RESTIC_PASSWORD_FILE:-}" ] || die "не задан RESTIC_PASSWORD_FILE"
[ -r "${RESTIC_PASSWORD_FILE}" ] || die "файл с паролем недоступен: $RESTIC_PASSWORD_FILE"
case "$STATE_DIR" in ""|"/") die "небезопасный OBOROT_BACKUP_STATE_DIR: '$STATE_DIR'";; esac
case "$RESTIC_REPOSITORY" in
  sftp:*|s3:*|b2:*|rest:*|azure:*|gs:*|swift:*|rclone:*) ;;
  *) die "RESTIC_REPOSITORY не удалённый: '$RESTIC_REPOSITORY'.
   Учение на локальном каталоге доказывает только то, что диск ещё жив." ;;
esac

# Секрет для расшифрования — только отдельной офсайт-копией и только файлом.
# Fail-closed: без неё учение не начинается. Мягкий вариант («не задан — не
# проверяем») здесь не годится по той же причине, по какой не годится пустая
# копия: получилось бы зелёное учение, которое ничего не говорит о том
# единственном, ради чего оно проводится.
[ -n "$RECOVERY_SECRET_FILE" ] || die "не задан OBOROT_RECOVERY_SECRET_FILE.
   Учение обязано доказать, что сохранённые токены МойСклада расшифровываются
   ОТДЕЛЬНОЙ копией OBOROT_SECRET, хранящейся вне этого сервера. Без секрета
   восстановленная база — это старые цифры без работающей интеграции.
   Заведите копию секрета вне машины и укажите путь к ней
   (см. deploy/backup.env.example)."
[ -r "$RECOVERY_SECRET_FILE" ] || die "копия секрета недоступна: $RECOVERY_SECRET_FILE"
[ -s "$RECOVERY_SECRET_FILE" ] || die "копия секрета пуста: $RECOVERY_SECRET_FILE"
[ "$RECOVERY_SECRET_FILE" != "${RESTIC_PASSWORD_FILE}" ] \
  || die "копия OBOROT_SECRET и пароль restic — это два разных секрета,
   и лежать они обязаны в разных файлах: $RECOVERY_SECRET_FILE"
# Секрет из окружения проверку обесценивает: она доказывала бы, что сервер знает
# свой собственный ключ, а не что офсайт-копия ключа подходит к офсайт-копии
# базы. Сюда же попадает OBOROT_SECRET, вписанный в backup.env, — то есть ключ,
# положенный рядом с бэкапом.
[ -z "${OBOROT_SECRET:-}" ] || die "OBOROT_SECRET пришёл из окружения (или из $CONFIG_FILE).
   Уберите его оттуда: учение должно проверять офсайт-копию секрета, а не ту,
   что и так лежит на этой машине."

# ОТКУДА берётся копия секрета. По повторному ревью 23.08: схема, в которой файл
# лежит на том же диске, что и база (`/opt/oborot/recovery-secret`), сама себе
# противоречила. Такой файл умирает вместе с машиной ровно так же, как база, и
# еженедельное учение с ним доказывало только то, что сервер знает собственный
# ключ, — то есть ничего сверх того, что и так известно.
#
# Проверяется минимально необходимое и строго техническое: файл лежит на ДРУГОЙ
# файловой системе, чем боевая база. Это отсекает единственный частый случай —
# локальный файл рядом с данными — и не отсекает ничего больше. Так же честно,
# как проверка `sftp:`/`s3:` у адреса хранилища: необходимое условие, не
# достаточное. Отдельно подключённый диск и отдельный домен отказа — не одно и
# то же; ЧЕЙ это диск и переживёт ли он потерю машины, скрипт узнать не может.
# Это остаётся за человеком и за OPS-4.
#
# Штатная схема на сервере: каталог, примонтированный только на чтение с той
# машины/из того хранилища, где секрет живёт постоянно, либо временная выгрузка
# из внешнего secret store в tmpfs на время учения. Юнит systemd дополнительно
# требует, чтобы точка монтирования была именно точкой монтирования
# (AssertPathIsMountPoint) — без неё учение по расписанию не стартует.
DOMAIN_REF="$DB"
[ -e "$DOMAIN_REF" ] || DOMAIN_REF="$(dirname "$DB")"
SECRET_DEV="$(fs_device "$RECOVERY_SECRET_FILE" || true)"
LIVE_DEV="$(fs_device "$DOMAIN_REF" || true)"
DOMAIN="отдельный"
if [ "$ALLOW_LOCAL_SECRET" = "1" ]; then
  # Явное послабление для стенда, где смонтировать нечего. Не отказ, но и не
  # молчаливый успех: в отметке остаётся domain=не-проверен, чтобы «зелёное
  # учение» нельзя было предъявить как доказательство отдельного хранения.
  DOMAIN="не-проверен"
  echo "   ВНИМАНИЕ: OBOROT_DRILL_ALLOW_LOCAL_SECRET=1 — откуда взята копия секрета, не проверяется." >&2
  echo "   Учение проверит расшифрование, но НЕ то, что ключ хранится вне этой машины." >&2
elif [ -z "$SECRET_DEV" ] || [ -z "$LIVE_DEV" ]; then
  die "не удалось определить файловые системы копии секрета и боевой базы
   ($RECOVERY_SECRET_FILE и $DOMAIN_REF). Без этого нельзя отличить копию,
   поданную извне, от файла на том же диске, что и данные."
elif [ "$SECRET_DEV" = "$LIVE_DEV" ]; then
  die "копия секрета лежит на той же файловой системе, что и боевая база:
   $RECOVERY_SECRET_FILE
   Такой файл умирает вместе с машиной ровно так же, как база, и учение с ним
   доказывает только то, что сервер знает свой собственный ключ. Подайте копию извне:
   каталог, примонтированный на чтение с другой машины, или временная выгрузка
   из внешнего secret store (см. deploy/backup.env.example, deploy/README.md).
   Осознанный прогон на стенде без монтирования:
   OBOROT_DRILL_ALLOW_LOCAL_SECRET=1 — тогда в отметке будет domain=не-проверен."
fi
[ -x "$VENV/bin/python" ] || die "нет $VENV/bin/python — нечем проверить расшифрование
   (OBOROT_VENV=$VENV)"

# Восстановление никогда не заменяет боевую базу само. Замену делает человек,
# осознанно, глядя на результат учения.
if [ -n "$OUTPUT" ]; then
  [ "$OUTPUT" != "$DB" ] || die "боевая база этим скриптом не заменяется: $DB"
  [ ! -e "$OUTPUT" ] && [ ! -L "$OUTPUT" ] || die "файл уже существует: $OUTPUT"
fi

mkdir -p "$STATE_DIR"
LOCK_FILE="$STATE_DIR/offsite.lock"
exec 9>"$LOCK_FILE"
flock -n 9 || die "офсайт-бэкап или учение уже выполняется ($LOCK_FILE)"

STAGE=""
cleanup() { [ -n "$STAGE" ] && [ -d "$STAGE" ] && rm -rf -- "$STAGE"; }
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

STAGE="$(mktemp -d "$STATE_DIR/drill.XXXXXX")"

echo "== 1/6 Проверяем хранилище =="
"$RESTIC" cat config >/dev/null 2>&1 || die "хранилище недоступно или не создано"
if [ "$FULL_CHECK" = "1" ]; then
  # --read-data читает сами блоки, а не только метаданные: без него «check ok»
  # означает лишь «оглавление на месте».
  "$RESTIC" check --read-data || die "restic check --read-data нашёл повреждение"
else
  echo "   БЫСТРАЯ ПРОВЕРКА: блоки данных не читаются (OBOROT_DRILL_FULL_CHECK=0)"
  "$RESTIC" check || die "restic check нашёл повреждение"
fi

echo "== 2/6 Скачиваем снимок $SNAPSHOT =="
"$RESTIC" restore "$SNAPSHOT" --tag oborot-db --host "$HOST_TAG" --target "$STAGE" \
  || die "restic restore не отработал"

RESTORED="$(find "$STAGE" -type f -name oborot.db -print 2>/dev/null | head -1 || true)"
[ -n "$RESTORED" ] || die "в снимке нет oborot.db"
EXTRA="$(find "$STAGE" -type f -name oborot.db -print 2>/dev/null | sed -n '2p' || true)"
[ -z "$EXTRA" ] || die "в снимке несколько oborot.db — непонятно, какой из них база"

echo "== 3/6 Целостность и содержимое =="
INTEG="$(sqlite3 "$RESTORED" "PRAGMA integrity_check;" 2>&1 || true)"
[ "$INTEG" = "ok" ] || die "восстановленная база битая: ${INTEG%%$'\n'*}"

ORGS="$(sqlite3 "$RESTORED" "SELECT COUNT(*) FROM orgs;" 2>/dev/null || echo 0)"
SALES="$(sqlite3 "$RESTORED" "SELECT COUNT(*) FROM sales;" 2>/dev/null || echo 0)"
STOCK="$(sqlite3 "$RESTORED" "SELECT COUNT(*) FROM stock_days;" 2>/dev/null || echo 0)"
echo "   организаций $ORGS · продаж $SALES · дней остатков $STOCK"
# Проверка строк, а не наличия таблиц. Пустая база — исправная база без данных;
# именно так «успешное учение» и превращается в ложное спокойствие.
[ "${ORGS:-0}" -gt 0 ] 2>/dev/null \
  || die "в восстановленной базе нет организаций.
   Схема цела, данных нет. Такая копия проходит любую структурную проверку и
   не годится ни для чего."

echo "== 4/6 Расшифровываем токены офсайт-копией секрета =="
# Секрет передаётся файлом, а не строкой в окружении: аргументы и окружение
# процесса видны в /proc любому, кто окажется на машине в этот момент.
TOKENS_RC=0
OBOROT_RECOVERY_SECRET_FILE="$RECOVERY_SECRET_FILE" \
  "$VENV/bin/python" "$HERE/check_restored_secrets.py" "$RESTORED" || TOKENS_RC=$?
case "$TOKENS_RC" in
  0) TOKENS="да" ;;
  3) TOKENS="нечего"
     # Не отказ, но и не успех: говорим прямо, чего учение НЕ доказало.
     echo "   ВНИМАНИЕ: в копии нет ни одного сохранённого токена интеграции."
     echo "   Учение доказало сохранность данных, но не сохранность доступа к МойСкладу."
     ;;
  *) die "офсайт-копия секрета не расшифровывает сохранённые токены.
   База восстановится, приложение поднимется — а синхронизация и запись в
   МойСклад работать не будут. Это и есть тот случай, ради которого проверка
   написана: сверьте OBOROT_SECRET на сервере с копией $RECOVERY_SECRET_FILE." ;;
esac

echo "== 5/6 Поднимаем приложение на восстановленной базе =="
if [ "$BOOT_APP" = "1" ]; then
  # Переиспользуем уже проверенный restore_test.sh: он принимает .gz, поднимает
  # приложение на отдельном порту и ждёт "db":true. Разделение труда: этот
  # скрипт отвечает за «данные доехали из хранилища», тот — за «на них
  # запускается приложение».
  gzip -c "$RESTORED" > "$STAGE/restored.db.gz" || die "не удалось сжать копию для проверки запуском"
  bash "$HERE/restore_test.sh" "$STAGE/restored.db.gz" \
    || die "приложение на восстановленной базе не поднялось"
else
  echo "   ПРОПУЩЕНО: OBOROT_DRILL_BOOT_APP=0."
  echo "   Учение доказало, что данные доехали, но не что на них работает приложение."
fi

echo "== 6/6 Итог =="
if [ -n "$OUTPUT" ]; then
  mkdir -p "$(dirname "$OUTPUT")"
  install -m 600 "$RESTORED" "$OUTPUT" || die "не удалось положить копию в $OUTPUT"
  echo "   проверенная копия: $OUTPUT"
fi

STAMP="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
# domain= в отметке — не украшение: по ней потом отвечают на вопрос «а учение
# точно читало ключ не с этой же машины?». `не-проверен` означает, что не точно.
printf '%s snapshot=%s host=%s orgs=%s boot_app=%s tokens=%s domain=%s\n' \
  "$STAMP" "$SNAPSHOT" "$HOST_TAG" "$ORGS" "$BOOT_APP" "$TOKENS" "$DOMAIN" \
  > "$STATE_DIR/last-offsite-drill.tmp"
mv "$STATE_DIR/last-offsite-drill.tmp" "$STATE_DIR/last-offsite-drill"
echo "УЧЕНИЕ ПРОЙДЕНО: $STAMP, организаций $ORGS, токены расшифрованы: $TOKENS"
if [ "$DOMAIN" = "не-проверен" ]; then
  echo "Откуда взята копия секрета — НЕ проверено (domain=не-проверен)."
else
  echo "Копия секрета прочитана с отдельной файловой системы; ЧЕЙ это диск —"
  echo "проверяет человек, скрипт физическое размещение доказать не может (OPS-4)."
fi
