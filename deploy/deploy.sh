#!/usr/bin/env bash
# Развёртывание «Оборота» на боевом сервере. Запускать НА СЕРВЕРЕ от root.
#
#   bash deploy/deploy.sh <commit-sha>   выкатить конкретный коммит
#   bash deploy/deploy.sh                выкатить текущую вершину main
#
# Почему именно так. Прод — обычный VPS с systemd-юнитом `oborot`, который
# запускает один процесс из /opt/oborot/app-src. До этого скрипта «деплой»
# означал «код как-то оказался на сервере», и ответить на вопрос «какая версия
# сейчас в бою» было нечем.
#
# Часть проверок ниже перенесена из PR #3 (ветка codex/ops-3-deploy-rollback):
# блокировка от параллельных выкладок, установка зависимостей ДО переключения
# кода, атомарная запись env, отказ на грязной рабочей копии и на коммите вне
# истории origin/main. Идеи оттуда, реализация и тесты — свои; отличия от
# оригинала отмечены по месту.
set -Eeuo pipefail

APP_DIR="${OBOROT_APP_DIR:-/opt/oborot/app-src}"
VENV="${OBOROT_VENV:-/opt/oborot/venv}"
VENV_ROOT="$(dirname "$VENV")"
VENV_KEEP="${OBOROT_VENV_KEEP:-3}"
PYTHON_BIN="${OBOROT_PYTHON:-$VENV/bin/python}"
DATA_DIR="${OBOROT_DATA_DIR:-/opt/oborot/data}"
ENV_FILE="${OBOROT_ENV_FILE:-/opt/oborot/env}"
SERVICE="${OBOROT_SERVICE:-oborot}"
HEALTH_URL="${OBOROT_HEALTH_URL:-http://127.0.0.1:8000/health/ready}"
STATE_DIR="${OBOROT_STATE_DIR:-/opt/oborot}"
LOCK_FILE="${OBOROT_LOCK_FILE:-$STATE_DIR/deploy.lock}"
PREVIOUS_FILE="${OBOROT_PREVIOUS_FILE:-$STATE_DIR/PREVIOUS_SHA}"
PREVIOUS_VENV_FILE="${OBOROT_PREVIOUS_VENV_FILE:-$STATE_DIR/PREVIOUS_VENV}"
HEALTH_ATTEMPTS="${OBOROT_HEALTH_ATTEMPTS:-30}"
HEALTH_DELAY="${OBOROT_HEALTH_DELAY:-2}"

# Драйвер выкладки — сам этот файл. Полный путь запоминается ДО первого `cd`:
# запуск `bash deploy/deploy.sh` даёт относительный `BASH_SOURCE`, и после
# перехода в каталог приложения сравнивать было бы уже не с чем.
DRIVER_SELF="${BASH_SOURCE[0]}"
case "$DRIVER_SELF" in /*) ;; *) DRIVER_SELF="$PWD/$DRIVER_SELF";; esac
DRIVER_REF="${OBOROT_DRIVER_REF:-origin/main}"
DRIVER_PATH="${OBOROT_DRIVER_PATH:-deploy/deploy.sh}"
# Два разных временных файла, и путать их нельзя. DRIVER_TMP — тот, который
# создал ЭТОТ процесс (и который, возможно, так и не пригодился).
# DRIVER_TMP_PARENT — тот, НА КОТОРОМ этот процесс исполняется после `exec`:
# его создал предыдущий процесс, а убрать за собой может только этот, потому
# что EXIT-трап у `exec` не выполняется. Пока это была одна переменная, второй
# путь затирался первым и файл драйвера оставался на диске.
DRIVER_TMP=""
DRIVER_TMP_PARENT="${OBOROT_DEPLOY_DRIVER_TMP:-}"

die() { printf 'ОШИБКА: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "не найдена команда: $1"; }
is_sha40() {
  case "$1" in ''|*[!0-9a-f]*) return 1;; esac
  [ "${#1}" = 40 ]
}

# Состояние выкладки: что уже изменено на проде и куда девалось прежнее
# окружение. Нужно для отката и для аварийной сети безопасности в trap EXIT.
CODE_SWITCHED=0
ENV_SWITCHED=0
VENV_SWAPPED=0
RELEASE_LOCK_USED=0
RESTART_STARTED=0   # точка невозврата пройдена: откат — уже решение человека
PREV_VENV_PATH=""   # где сейчас лежит окружение, работавшее до этой выкладки
VENV_HOLD=""        # каталог, который ОБЯЗАН оказаться на месте $VENV, если его нет

# Цель отката — не «прежний HEAD», а «прежний ОТЛИЧАЮЩИЙСЯ релиз». Разница
# видна только при повторной выкладке того же коммита, и она стоила прода
# честного отката (OPS-8, журнал выпуска 27.08.2026): второй заход тем же SHA
# записывал `PREVIOUS_SHA` равным текущему коммиту, печатал откат на самого
# себя и снимал защиту уборки с настоящего отложенного окружения.
SAME_SHA=0
REPAIR_ONLY=0
ROLLBACK_SHA=""
ROLLBACK_VENV=""

# Запись OBOROT_COMMIT во временный файл и mv поверх. Прежняя версия правила
# env через `sed -i`: обрыв посреди правки оставлял бы урезанный файл
# окружения, а без него приложение не стартует вовсе. mv в пределах одной
# файловой системы атомарен.
set_commit_env() {
  local sha="$1" tmp
  tmp="$(mktemp "$STATE_DIR/env.XXXXXX")" || return 1
  if grep -q '^OBOROT_COMMIT=' "$ENV_FILE"; then
    sed "s/^OBOROT_COMMIT=.*/OBOROT_COMMIT=$sha/" "$ENV_FILE" > "$tmp" \
      || { rm -f "$tmp"; return 1; }
  else
    { cat "$ENV_FILE"; printf '\nOBOROT_COMMIT=%s\n' "$sha"; } > "$tmp" \
      || { rm -f "$tmp"; return 1; }
  fi
  chmod --reference="$ENV_FILE" "$tmp" 2>/dev/null || chmod 600 "$tmp"
  mv "$tmp" "$ENV_FILE" || { rm -f "$tmp"; return 1; }
}

# ОКРУЖЕНИЕ НА РЕЛИЗ. Идея — из ветки Codex codex/ops-3-hardening, и она
# строго лучше того, что было у меня: я ставил зависимости целевого коммита в
# ЖИВОЙ venv до переключения кода. Это спасало прод от неудачной установки, но
# ломало откат: `deploy.sh <прежний-sha>` возвращал код на прежний коммит и
# оставлял ему НОВЫЕ библиотеки. Откат восстанавливал половину состояния.
#
# Теперь окружение каждого релиза собирается отдельно и подставляется целиком.
# Прежнее не удаляется, а откладывается под именем venv-<прежний-sha>.
#
# Своё сверх источника: откат переиспользует отложенное окружение, если оно
# цело. В аварии сеть — не то, на что стоит рассчитывать, а пересборка venv
# без сети невозможна. Там, где у источника откат зависел от pip, здесь он
# сводится к переименованию каталога.
#
# Отличие от PR #3 сохраняется: ставится только requirements.lock. Установка
# requirements.txt с диапазонами означала бы, что фиксация версий не значит
# ничего (решение владельца 23.08.2026, fail-closed).
# Годность отложенного окружения проверяется по метке ВНУТРИ него, а не по
# имени каталога. Имя ставится по коммиту, который был выкачен на момент
# подмены; если по какой-то причине оно соврало, переиспользование подсунуло бы
# релизу чужие библиотеки — и молча, потому что снаружи всё выглядит правильно.
# Метка внутри такого не позволяет: расхождение означает пересборку.
#
# Вызов pip — ТОЛЬКО через `python -m pip`, и это не вкусовщина. Каталог
# окружения здесь переезжает дважды (staging → $VENV → venv-<sha>), а в
# консольных обёртках `bin/pip`, `bin/uvicorn` и прочих зашит АБСОЛЮТНЫЙ путь
# интерпретатора в первой строке. После переименования каталога такая обёртка
# перестаёт запускаться вовсе («bad interpreter»), тогда как `bin/python` —
# символическая ссылка на системный интерпретатор, и переезда не замечает.
# С прежним кодом это ломало не выкладку, а ОТКАТ: проверка годности отложенного
# окружения дёргала `bin/pip check`, всегда получала отказ — и «переиспользуем
# готовое окружение без сети» молча превращалось в пересборку через сеть,
# то есть ровно в то, чего D-44 и должен был избежать.
#
# ЧЕГО ЭТОГО НЕ ХВАТИЛО (OPS-6, 27.08.2026). Обход обёрток спас выкладку и
# откат, но сами обёртки так и остались сломанными — в том числе в бою. На проде
# `/opt/oborot/venv/bin/pip` начинался с `#!/opt/oborot/.venv-staging.588121/...`;
# каталога с таким именем давно нет, прямой вызов отдавал 127. Выкладка при этом
# была зелёной, потому что `verify_live_venv` спрашивал только `python -m pip` —
# то есть релизный gate пропускал окружение с нерабочими entrypoint'ами и молчал
# об этом. Обход перестал быть проверкой ровно там, где стал привычкой.
#
# Теперь первая строка таких обёрток чинится на финальном пути, локально и без
# сети (repair_console_shebangs), а проверка перестала быть слепой: обёртка
# обязана ЗАПУСТИТЬСЯ, иначе выкладка откатывается до перезапуска.
# Правило «зависимости ставятся и проверяются только через `python -m pip`» этим
# не ослаблено и не отменено: прямой вызов обёртки во всём скрипте ровно один,
# он проверочный (`pip --version`), ничего не ставит и ничего не меняет.
release_venv_ok() {
  local dir="$1"
  local sha="$2"
  [ -d "$dir" ] || return 1
  [ -x "$dir/bin/python" ] || return 1
  [ -f "$dir/RELEASE_SHA" ] || return 1
  [ "$(cat "$dir/RELEASE_SHA" 2>/dev/null)" = "$sha" ] || return 1
  "$dir/bin/python" -m pip check >/dev/null 2>&1
}

install_into() {
  local sha="$1" venv="$2" req rc=0
  if git cat-file -e "$sha:requirements.lock" 2>/dev/null; then
    req="$(mktemp "$STATE_DIR/requirements.XXXXXX")" || return 1
    git show "$sha:requirements.lock" > "$req" || { rm -f "$req"; return 1; }
    "$venv/bin/python" -m pip install -q -r "$req" || rc=1
    [ "$rc" = 0 ] && { "$venv/bin/python" -m pip check || rc=1; }
    rm -f "$req"
    [ "$rc" = 0 ] && RELEASE_LOCK_USED=1
    return "$rc"
  fi
  if [ "${OBOROT_ALLOW_NO_LOCK:-0}" != "1" ]; then
    printf 'в коммите %s нет requirements.lock — сборка невоспроизводима.\n' "$sha" >&2
    printf 'осознанный откат на старый коммит: OBOROT_ALLOW_NO_LOCK=1 bash deploy/deploy.sh %s\n' "$sha" >&2
    return 1
  fi
  req="$(mktemp "$STATE_DIR/requirements.XXXXXX")" || return 1
  git show "$sha:requirements.txt" > "$req" || { rm -f "$req"; return 1; }
  "$venv/bin/python" -m pip install -q -r "$req" || rc=1
  rm -f "$req"
  return "$rc"
}

# Единственное место, где решается «это python-обёртка и вот её командная
# строка из шебанга». Печатает `<интерпретатор>[ аргументы]` — и только для
# обычного исполняемого файла с абсолютным шебангом на python; во всех
# остальных случаях не печатает ничего.
#
# Одно место здесь принципиально: «какие файлы вообще подлежат правилу» нужно и
# починке, и проверке. Разъедься они в этом — проверка начала бы зеленеть ровно
# на том, чего починка не трогала, а это тот же класс дефекта, который OPS-6 и
# закрывает. Само правило («интерпретатор обязан быть ровно $VENV/bin/python»)
# каждая из них применяет у себя, и применяет одинаково.
#
# Что сознательно пропускается:
#   * симлинки — `bin/python`, `bin/python3`, `bin/python3.12` ссылаются на
#     системный интерпретатор и переезда каталога не замечают вовсе;
#   * файлы без бита исполнения — `activate`, `Activate.ps1` и прочие: их не
#     запускают, их читают;
#   * шебанги не на python (`#!/bin/sh`) и относительные/`env`-шебанги —
#     чужая ответственность, и трогать их починка не имеет права;
#   * бинарники — их первые байты под `#!/` не подходят.
console_shebang_cmd() {
  local f="$1" first cmd interp
  [ ! -L "$f" ] && [ -f "$f" ] && [ -x "$f" ] || return 0
  first=""
  IFS= read -r first < "$f" || true
  case "$first" in '#!/'*) ;; *) return 0;; esac
  cmd="${first#\#!}"
  interp="${cmd%%[[:space:]]*}"
  case "${interp##*/}" in python*) ;; *) return 0;; esac
  printf '%s\n' "$cmd"
}

# ПОЧИНКА КОНСОЛЬНЫХ ОБЁРТОК НА ФИНАЛЬНОМ ПУТИ (OPS-6).
#
# `bin/pip`, `bin/uvicorn` и прочие обёртки — обычные текстовые файлы, в первой
# строке которых зашит АБСОЛЮТНЫЙ путь интерпретатора того каталога, где venv
# собирали. Каталог релиза здесь переезжает (staging → $VENV, а при
# переиспользовании отложенного окружения ещё и venv-<sha> → staging → $VENV),
# и после переезда ядро не находит интерпретатора из первой строки: обёртка не
# запускается вовсе. Проверено на настоящем venv, а не только на подставном:
# перенос каталога даёт `bad interpreter ... no such file or directory` и код
# 127, тогда как `python -m pip` в том же окружении отвечает нормально.
#
# Починка сознательно самая маленькая из возможных и БЕЗ СЕТИ — ни pip, ни
# пересборки окружения, ни ensurepip. Переписывается только ПЕРВАЯ СТРОКА и
# только у распознанных абсолютных python-обёрток, чей интерпретатор не равен
# ровно `$VENV/bin/python`. Аргументы шебанга (`-sE` и подобное) сохраняются,
# тело файла не трогается ни байтом: окружение релиза обязано остаться ровно
# тем, что собрано по requirements.lock.
#
# Приведение к точному целевому пути, а не «починка сломанного», — исправление
# по внешнему ревью (corrective #1 к этому же пакету). Первая версия правила
# звучала как «интерпретатор перестал существовать», и это пропускало худший
# случай: живой, запускаемый, но ЧУЖОЙ интерпретатор. Такая обёртка не выглядит
# сломанной ничем — она работает, — но работает окружением другого релиза.
# Заодно к цели приводится и `#!$VENV/bin/python3.12`: интерпретатор тот же, но
# «почти совпадает» — это не свойство, которое можно проверить, а нормализация
# стоит одной строки.
#
# Целью ставится `$VENV/bin/python`, а не `bin/python3.12`: наличие первого —
# инвариант этого скрипта (он проверяется в разделе 1/6 и требуется для отката),
# а точная минорная версия в имени — нет.
#
# Почему сеть здесь недопустима отдельным пунктом: это окно между подменой
# окружения и перезапуском службы. Поход в сеть в нём добавил бы выкладке ещё
# одну причину падать, причём внешнюю, — а чинить надо строку в файле.
repair_console_shebangs() {
  local venv="$1" f cmd interp rest tmp fixed=0
  for f in "$venv"/bin/*; do
    cmd="$(console_shebang_cmd "$f")"
    [ -n "$cmd" ] || continue
    interp="${cmd%%[[:space:]]*}"
    # Условие — РАВЕНСТВО целевому пути, а не «интерпретатор существует».
    # Разница не косметическая, и она стоила отдельного отката по ревью
    # (OPS-6, corrective #1). Проверка «файл на месте» пропускает самый вредный
    # случай: шебанг указывает на ЖИВОЙ, но ЧУЖОЙ интерпретатор. На сервере
    # такие живут по построению — `OBOROT_VENV_KEEP` держит рядом отложенные
    # `venv-<sha>` прежних релизов, и `venv-<CURRENT>` создаётся этой же
    # подменой. Обёртка с таким шебангом запускается и потому выглядит
    # исправной, но исполняется окружением ПРОШЛОГО релиза: чужие библиотеки,
    # чужие версии — и зелёный gate поверх этого.
    [ "$interp" = "$venv/bin/python" ] && continue
    rest=""
    case "$cmd" in *[[:space:]]*) rest=" ${cmd#*[[:space:]]}";; esac
    # Правка через временный файл и mv: обрыв посреди записи оставил бы обрубок
    # вместо обёртки — та же причина, по которой env пишется атомарно.
    tmp="$f.oborot-shebang.$$"
    rm -f "$tmp"
    { printf '#!%s/bin/python%s\n' "$venv" "$rest"; tail -n +2 "$f"; } > "$tmp" \
      || { rm -f "$tmp"; return 1; }
    chmod --reference="$f" "$tmp" 2>/dev/null || chmod 755 "$tmp"
    mv "$tmp" "$f" || { rm -f "$tmp"; return 1; }
    fixed=$((fixed + 1))
  done
  [ "$fixed" = 0 ] \
    || echo "   консольных обёрток приведено к $VENV/bin/python: $fixed"
  return 0
}

# Проверка обёрток — независимая от починки и fail-closed. Смотрит на результат,
# а не на то, что починка о себе сообщила: сначала каждая распознанная обёртка в
# $VENV/bin обязана указывать РОВНО на `$VENV/bin/python`, а затем
# представительная обёртка обязана РЕАЛЬНО ЗАПУСТИТЬСЯ.
#
# «Ровно», а не «на что-нибудь запускаемое» — потому что второе проверкой не
# является: обёртка, ссылающаяся на живой интерпретатор соседнего релиза,
# запускается прекрасно и делает при этом не то. Отчёт починки здесь ничего не
# значит по построению: если она отчиталась об успехе, а файл остался прежним,
# поймать это должна именно эта функция.
#
# `pip --version` выбран представителем не случайно: pip есть в любом venv,
# созданном `python -m venv`, вызов ничего не устанавливает, никуда не ходит и
# ничего не меняет — он ровно тот, что ломался в бою. Отсутствие обёртки — тоже
# отказ: раз её нет, доказывать нечем, а молча пропущенная проверка и есть тот
# дефект, из-за которого сломанный entrypoint доехал до прода.
verify_console_entrypoints() {
  local f cmd interp bad=""
  for f in "$VENV"/bin/*; do
    cmd="$(console_shebang_cmd "$f")"
    [ -n "$cmd" ] || continue
    interp="${cmd%%[[:space:]]*}"
    # Требуется РОВНО целевой интерпретатор. «Указывает на что-то запускаемое»
    # проверкой не является: живой чужой интерпретатор её проходил, и обёртка
    # исполнялась окружением прошлого релиза при зелёной выкладке.
    [ "$interp" = "$VENV/bin/python" ] || bad="$bad ${f##*/}($interp)"
  done
  if [ -n "$bad" ]; then
    echo "   консольные обёртки указывают не на $VENV/bin/python:$bad" >&2
    return 1
  fi
  [ -f "$VENV/bin/pip" ] && [ -x "$VENV/bin/pip" ] \
    || { echo "   в $VENV нет исполняемой консольной обёртки bin/pip" >&2; return 1; }
  "$VENV/bin/pip" --version >/dev/null 2>&1 \
    || { echo "   $VENV/bin/pip не запускается на финальном пути" >&2; return 1; }
  return 0
}

# Окружение проверяется НА ФИНАЛЬНОМ ПУТИ, после подмены, а не на staging.
# Проверка на staging доказывает только то, что окружение работало по прежнему
# адресу; всё, что ломается именно переездом, она пропускает по построению.
verify_live_venv() {
  local sha="$1"
  [ -x "$VENV/bin/python" ] || { echo "   нет $VENV/bin/python" >&2; return 1; }
  [ -f "$VENV/RELEASE_SHA" ] || { echo "   в $VENV нет метки RELEASE_SHA" >&2; return 1; }
  [ "$(cat "$VENV/RELEASE_SHA" 2>/dev/null)" = "$sha" ] \
    || { echo "   метка окружения не совпадает с релизом" >&2; return 1; }
  "$VENV/bin/python" -m pip --version >/dev/null 2>&1 \
    || { echo "   $VENV/bin/python -m pip не работает на финальном пути" >&2; return 1; }
  if [ "$RELEASE_LOCK_USED" = 1 ]; then
    "$VENV/bin/python" -m pip check >/dev/null 2>&1 \
      || { echo "   pip check на финальном пути не проходит" >&2; return 1; }
  fi
  # Проверки выше говорят про библиотеки и метку релиза; они целиком идут через
  # `python -m pip` и остаются как были. Ниже — про то, что ломается ИМЕННО
  # переездом каталога и мимо них проходило (OPS-6).
  verify_console_entrypoints || return 1
  return 0
}

prepare_release_venv() {
  # Раздельные строки не для красоты: bash раскрывает ВСЕ слова команды `local`
  # до её выполнения, поэтому `local sha="$1" cached="...$sha"` под `set -u`
  # падает с «unbound variable» — переменная ещё не присвоена в момент подстановки.
  local sha="$1"
  local staging="$2"
  local cached="$VENV_ROOT/venv-$sha"
  if release_venv_ok "$cached" "$sha"; then
    echo "   окружение этого релиза уже собрано — сеть не нужна"
    # Годность уже доказана `pip check` выше — на финальном пути её проверим
    # ещё раз, после подмены.
    RELEASE_LOCK_USED=1
    mv "$cached" "$staging" || return 1
    return 0
  fi
  rm -rf -- "$cached" "$staging"
  "$PYTHON_BIN" -m venv "$staging" || { rm -rf -- "$staging"; return 1; }
  install_into "$sha" "$staging" || { rm -rf -- "$staging"; return 1; }
  printf '%s\n' "$sha" > "$staging/RELEASE_SHA" || { rm -rf -- "$staging"; return 1; }
  return 0
}

# Подмена в два переименования. Живой процесс держит свои файлы по inode и
# переезда каталога не замечает — он в любом случае будет перезапущен ниже.
#
# VENV_HOLD выставляется РОВНО на то время, пока $VENV не существует. Это не
# бухгалтерия ради бухгалтерии: если скрипт умрёт именно в этом промежутке
# (сигнал, ошибка ФС), на месте рабочего окружения останется пустота, а сервис
# без окружения не поднимется вообще — то есть неудачная выкладка превратится
# в полноценную аварию. Сеть безопасности в trap EXIT читает этот путь.
swap_release_venv() {
  local staging="$1" keep="$VENV_ROOT/venv-$CURRENT" held="$VENV_ROOT/.venv-held.$$"
  rm -rf -- "$held"
  VENV_HOLD="$held"
  if ! mv "$VENV" "$held"; then
    VENV_HOLD=""
    return 1
  fi
  if ! mv "$staging" "$VENV"; then
    if mv "$held" "$VENV"; then VENV_HOLD=""; fi
    return 1
  fi
  VENV_HOLD=""
  PREV_VENV_PATH="$held"
  # С этой секунды в $VENV лежит окружение НОВОГО релиза, и откат обязан вернуть
  # прежнее. Поэтому флаг ставится ЗДЕСЬ, а не строкой у вызывающего: ниже есть
  # ещё одно переименование, и оно умеет падать. Пока флаг выставлялся снаружи,
  # падение последнего `mv` возвращало 1 раньше, чем `VENV_SWAPPED=1` успевало
  # выполниться, — и `rollback_release` молча пропускал возврат окружения: код и
  # env откатывались на прежний релиз, а в $VENV оставались библиотеки нового.
  # Состояние, которого нет ни в одном коммите, — ровно то, ради чего написан
  # D-46. Найдено внешним ревью 23.08, проверено инъекцией сбоя на этом `mv`.
  VENV_SWAPPED=1
  rm -rf -- "$keep"
  # `[ -e "$keep" ]` — не перестраховка. Если каталог пережил `rm` (права,
  # занятый файл), `mv` не заменит его, а ВЛОЖИТ прежнее окружение внутрь:
  # PREV_VENV_PATH указывал бы на venv-<sha>, который venv не является, и откат
  # подставил бы сервису каталог без интерпретатора. Это отказ, а не успех.
  if [ -e "$keep" ] || ! mv "$held" "$keep"; then
    echo "   ВНИМАНИЕ: прежнее окружение осталось как $held" >&2
    return 1
  fi
  PREV_VENV_PATH="$keep"
  echo "   прежнее окружение отложено: $keep"
}

# Обратная операция: вернуть на место окружение, работавшее до этой выкладки.
# Порядок и здесь выбран так, чтобы $VENV отсутствовал минимальное время, а при
# ВТОРИЧНОМ сбое (не получилось поставить прежнее) на месте оказалось хоть
# что-то рабочее — пусть даже окружение неудачного релиза.
restore_previous_venv() {
  local aside="$VENV_ROOT/.venv-rollback.$$"
  [ -n "$PREV_VENV_PATH" ] && [ -d "$PREV_VENV_PATH" ] || return 1
  rm -rf -- "$aside"
  if [ -e "$VENV" ]; then
    VENV_HOLD="$aside"
    if ! mv "$VENV" "$aside"; then
      VENV_HOLD=""
      return 1
    fi
  fi
  if ! mv "$PREV_VENV_PATH" "$VENV"; then
    if [ -d "$aside" ] && mv "$aside" "$VENV"; then VENV_HOLD=""; fi
    return 1
  fi
  VENV_HOLD=""
  PREV_VENV_PATH=""
  rm -rf -- "$aside"
  return 0
}

# Откат всего, что успели изменить ДО первого перезапуска сервиса. В этом окне
# он безопасен и потому обязателен: данные ещё никто не трогал, миграции не
# выполнялись, приложение работает на прежнем коде в своей памяти. Оставить прод
# в состоянии «код нового релиза, окружение неизвестно чьё, сервис ещё старый»
# хуже любого из двух согласованных состояний.
#
# Это НЕ противоречит решению «автоматического отката нет» (D-44): там речь про
# откат ПОСЛЕ перезапуска, когда новый код уже мог тронуть базу. Здесь — про
# отмену собственных недоделанных действий.
rollback_release() {
  local reason="$1" ok=1
  trap - ERR
  echo >&2
  echo "СБОЙ ДО ПЕРЕЗАПУСКА: $reason" >&2
  echo "Сервис ещё не перезапускался, данные не менялись — возвращаю прод на $CURRENT." >&2
  if [ "$VENV_SWAPPED" = 1 ]; then
    if restore_previous_venv; then
      echo "   окружение возвращено: $VENV снова от $CURRENT" >&2
    else
      ok=0
      echo "   ОКРУЖЕНИЕ ВЕРНУТЬ НЕ УДАЛОСЬ. В $VENV осталось окружение релиза $SHA." >&2
      echo "   Руками: bash deploy/deploy.sh $CURRENT (пересоберёт окружение прежнего релиза)." >&2
    fi
  fi
  if [ "$ENV_SWITCHED" = 1 ]; then
    if set_commit_env "$CURRENT"; then
      echo "   OBOROT_COMMIT возвращён на $CURRENT" >&2
    else
      ok=0
      echo "   OBOROT_COMMIT ВЕРНУТЬ НЕ УДАЛОСЬ: проверьте $ENV_FILE руками." >&2
    fi
  fi
  if [ "$CODE_SWITCHED" = 1 ]; then
    if git checkout --detach --force "$CURRENT" >/dev/null 2>&1; then
      echo "   код возвращён на $CURRENT" >&2
    else
      ok=0
      echo "   КОД ВЕРНУТЬ НЕ УДАЛОСЬ: в $APP_DIR остался $SHA." >&2
    fi
  fi
  if [ "$ok" = 1 ]; then
    echo "Прод в прежнем состоянии, выкладка не выполнена." >&2
  else
    echo "ОТКАТ НЕПОЛНЫЙ — разберитесь руками ДО перезапуска сервиса." >&2
  fi
  exit 1
}

# Старые окружения занимают место и нужны только для отката на недавнее.
#
# Два правила, и оба появились по внешнему ревью 23.08.
#
# Первое: уборка НИКОГДА не трогает непосредственную цель отката. Сортировка идёт
# по времени изменения, а отложенное окружение переезжает переименованием и
# сохраняет СТАРЫЙ mtime — то есть оказывается в конце списка. При небольшом
# OBOROT_VENV_KEEP скрипт своими руками удалял бы каталог, на который сам же
# указывает в подсказке про откат, и лишал бы прод возврата без сети.
#
# Второе: место в квоте цель отката всё-таки занимает. Иначе `OBOROT_VENV_KEEP=2`
# тихо означало бы три каталога, и настройка врала бы про размер на диске.
# Третье правило добавлено OPS-8, и оно закрывает дыру в первых двух. Они
# защищали `venv-$CURRENT` и окружение, отложенное ЭТОЙ выкладкой. При повторной
# выкладке того же коммита оба указывают на один и тот же каталог текущего
# релиза, а настоящая цель отката — окружение прежнего ОТЛИЧАЮЩЕГОСЯ релиза —
# оказывалась незащищённой и уезжала первой: она переехала переименованием,
# сохранила старый mtime и потому стоит в конце списка. Теперь защищается и
# записанная цель отката; место в квоте она, как и остальные, занимает.
prune_release_venvs() {
  local line path n=0 k keeps
  keeps=$'\n'
  for k in "$VENV_ROOT/venv-$CURRENT" "${PREV_VENV_PATH:-}" "${ROLLBACK_VENV:-}"; do
    [ -n "$k" ] || continue
    case "$keeps" in *$'\n'"$k"$'\n'*) continue;; esac
    keeps="$keeps$k"$'\n'
    [ -d "$k" ] && n=$((n + 1))
  done
  # Неудача любого звена не должна валить скрипт уже ПОСЛЕ успешной выкладки:
  # прод жив, а деплой отчитался бы об ошибке. Уборка старых каталогов не стоит
  # ложной тревоги — отсюда `|| true` на удалении и `return 0` в конце.
  while IFS= read -r line; do
    path="${line#* }"
    case "$keeps" in *$'\n'"$path"$'\n'*) continue;; esac
    n=$((n + 1))
    [ "$n" -gt "$VENV_KEEP" ] || continue
    rm -rf -- "$path" || true
  done < <(find "$VENV_ROOT" -maxdepth 1 -type d -name 'venv-*' -printf '%T@ %p\n' \
             2>/dev/null | sort -rn)
  return 0
}

wait_ready() {
  local i body
  for i in $(seq 1 "$HEALTH_ATTEMPTS"); do
    if body="$(curl -fsS "$HEALTH_URL" 2>/dev/null)" \
       && printf '%s' "$body" | grep -q '"status":"ok"'; then
      printf '%s\n' "$body"
      return 0
    fi
    sleep "$HEALTH_DELAY"
  done
  return 1
}

# Одиночная проба здоровья, без ожидания. Нужна там, где служба УЖЕ должна
# работать и вопрос стоит «жива ли она сейчас», а не «поднялась ли после
# перезапуска»: ждать в этом случае минуту нечего и незачем.
service_ready_now() {
  local body
  body="$(curl -fsS "$HEALTH_URL" 2>/dev/null)" || return 1
  printf '%s' "$body" | grep -q '"status":"ok"'
}

# Подсказка про откат печатается ровно одна и берётся из вычисленной цели, а не
# из «прежнего HEAD». Пустая цель называется вслух: молчаливый `deploy.sh` без
# аргумента увёл бы дежурного на вершину main вместо отката.
rollback_hint() {
  if [ -n "$ROLLBACK_SHA" ] && [ "$ROLLBACK_SHA" != "$SHA" ]; then
    printf 'откат: bash deploy/deploy.sh %s' "$ROLLBACK_SHA"
  else
    printf 'отката одной командой нет: прежний отличающийся релиз не записан'
  fi
}

# ДРАЙВЕР ВЫКЛАДКИ ОБНОВЛЯЕТСЯ ДО ВЫКЛАДКИ, А НЕ ВМЕСТЕ С НЕЙ (OPS-8).
#
# Дефект доказан выпуском 27.08.2026 и воспроизводится всегда. `bash` читает
# скрипт из открытого дескриптора по мере исполнения, а `git checkout` в
# середине выкладки заменяет файл НОВЫМ inode. Прежний дескриптор остаётся на
# старом (уже отвязанном) содержимом — значит весь прогон доигрывает ПРЕЖНЯЯ
# реализация скрипта, включая все проверки, которых в ней ещё нет. На проде это
# дало зелёный первый заход, на котором починка консольных обёрток не
# исполнялась вовсе, а прямой `venv/bin/pip` остался нерабочим.
#
# Симметричная форма того же — откат: `deploy.sh <старый-sha>` кладёт на диск
# СТАРЫЙ драйвер, и следующая выкладка стартует уже с него. Выкладка тем самым
# понижала бы сама себя.
#
# Поэтому и вперёд, и назад работает драйвер из ЗАЩИЩЁННОГО `origin/main`, а не
# из целевого коммита: защищённая ветка — единственное место, про которое
# известно, что содержимое прошло ревью и строгий CI.
#
# Четыре решения, каждое об одном классе отказа:
#
#   * МЕСТО. Подстановка стоит до блокировки и до любой мутации кода, env,
#     окружения, базы и службы. `exec` заменяет процесс целиком — второго
#     процесса выкладки не появляется, поэтому и второй «полосы» деплоя тоже:
#     PID тот же, блокировку ниже берёт ровно один процесс. Проносить сквозь
#     `exec` уже взятый дескриптор лока было бы тоньше и хуже проверяемо.
#   * РЕКУРСИЯ. Счётчик глубины передаётся наследнику. Вторая несходимость —
#     отказ, а не новый круг: если после подстановки содержимое всё ещё
#     расходится, значит происходит что-то, чего скрипт не понимает, и лучший
#     исход здесь — «выкладка не начата».
#   * ВРЕМЕННЫЙ ФАЙЛ. У `exec` EXIT-трап родителя не выполняется вовсе, поэтому
#     убирать за собой обязан наследник: путь передаётся ему в окружении, и его
#     EXIT-трап удаляет файл при любом исходе. Если сам `exec` не удался, файл
#     убирает трап этого процесса.
#   * СЕТЬ. `git fetch` здесь — новая внешняя причина упасть, и это осознанно:
#     она fail-closed и срабатывает ДО первой мутации, то есть худший исход —
#     «выкладка не начата», а не «прод в промежуточном состоянии».
bootstrap_driver() {
  local depth="${OBOROT_DEPLOY_BOOTSTRAP_DEPTH:-0}" tmp
  case "$depth" in ''|*[!0-9]*) die "испорчен счётчик подстановки драйвера: '$depth'";; esac

  # Наследник не ходит в сеть повторно: родитель уже сходил, и ссылки на месте.
  if [ "$depth" = 0 ]; then
    git fetch --all --tags --prune \
      || die "не удалось получить $DRIVER_REF — выкладка не начата, прод не тронут"
  fi
  git rev-parse --verify --quiet "$DRIVER_REF^{commit}" >/dev/null \
    || die "не найден $DRIVER_REF — нечем определить актуальный драйвер выкладки"
  git cat-file -e "$DRIVER_REF:$DRIVER_PATH" 2>/dev/null \
    || die "в $DRIVER_REF нет $DRIVER_PATH — нечем определить актуальный драйвер выкладки"

  tmp="$(mktemp "$STATE_DIR/.deploy-driver.XXXXXX")" \
    || die "не удалось создать временный файл драйвера в $STATE_DIR"
  DRIVER_TMP="$tmp"
  git show "$DRIVER_REF:$DRIVER_PATH" > "$tmp" \
    || die "не удалось прочитать $DRIVER_PATH из $DRIVER_REF"

  if cmp -s "$tmp" "$DRIVER_SELF"; then
    rm -f "$tmp"
    DRIVER_TMP=""
    echo "драйвер выкладки актуален ($DRIVER_REF)"
    return 0
  fi
  if [ "$depth" -ge 1 ]; then
    die "драйвер не сошёлся с $DRIVER_REF после подстановки — выкладка остановлена до любых изменений"
  fi
  chmod 755 "$tmp"
  echo "драйвер из $DRIVER_REF отличается от запущенного — перезапускаюсь на нём"
  export OBOROT_DEPLOY_BOOTSTRAP_DEPTH=$((depth + 1))
  export OBOROT_DEPLOY_DRIVER_TMP="$tmp"
  exec bash "$tmp" "$@"
  die "не удалось запустить актуальный драйвер выкладки из $DRIVER_REF"
}

