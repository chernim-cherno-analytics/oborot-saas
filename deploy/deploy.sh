# Сеть безопасности. Ставится ДО первого действия с окружением: если скрипт
# умрёт в тот момент, когда $VENV переехал, а новый ещё не встал на его место,
# сервис останется без интерпретатора вообще. Это единственное состояние, из
# которого прод не поднимается сам, — поэтому оно лечится даже в аварийном
# выходе, и только оно.
on_exit() {
  local rc=$? cand
  # Временный файл драйвера убирает тот процесс, который на нём исполняется:
  # у `exec` EXIT-трап предыдущего не выполняется вовсе. Удалять файл,
  # исполняемый прямо сейчас, безопасно: сюда управление приходит уже на выходе,
  # и дочитывать скрипт оболочка не будет.
  for cand in "${DRIVER_TMP:-}" "${DRIVER_TMP_PARENT:-}"; do
    [ -n "$cand" ] && [ -e "$cand" ] && rm -f "$cand"
  done
  if [ -n "${STAGING_VENV:-}" ] && [ -e "$STAGING_VENV" ]; then
    rm -rf -- "$STAGING_VENV"
  fi
  if [ ! -e "$VENV" ]; then
    for cand in "$VENV_HOLD" "$PREV_VENV_PATH" "$VENV_ROOT/venv-${CURRENT:-}"; do
      [ -n "$cand" ] && [ -d "$cand" ] || continue
      if mv "$cand" "$VENV"; then
        echo "АВАРИЙНО: рабочее окружение восстановлено из $cand" >&2
        break
      fi
    done
  fi
  [ -e "$VENV" ] || echo "КРИТИЧНО: $VENV отсутствует, сервис без окружения не поднимется.
   Соберите заново: bash deploy/deploy.sh ${CURRENT:-<sha>}" >&2
  return $rc
}
trap on_exit EXIT

# Сигналы. Без этого трапа SIGTERM (и Ctrl-C, и обрыв ssh) убивал bash сразу:
# EXIT-трап не выполнялся, откат не делался, и прод оставался ровно в том
# состоянии, против которого написан D-46 — код нового релиза, окружение
# нового, служба ещё старая и живая, поэтому никто ничего не замечает.
# Граница здесь та же, что у ошибок: до первого перезапуска сигнал означает
# полный откат, после — обычный отказ, потому что откат ПОСЛЕ перезапуска
# остаётся решением человека (D-44).
on_signal() {
  local sig="$1"
  trap - INT TERM HUP ERR
  if [ "$RESTART_STARTED" = 0 ] \
     && { [ "$CODE_SWITCHED" = 1 ] || [ "$ENV_SWITCHED" = 1 ] || [ "$VENV_SWAPPED" = 1 ]; }; then
    rollback_release "выкладка прервана сигналом $sig"
  fi
  die "выкладка прервана сигналом $sig"
}
trap 'on_signal INT' INT
trap 'on_signal TERM' TERM
trap 'on_signal HUP' HUP

echo "== 2/7 Драйвер выкладки =="
# До блокировки — сознательно: `exec` заменяет процесс, второй полосы деплоя не
# возникает, а лок ниже берёт ровно один процесс с тем же PID.
bootstrap_driver "$@"

# Блокировка от параллельных выкладок. flock держит дескриптор до конца
# процесса и освобождается даже после SIGKILL, поэтому «забытый» лок не
# превращается в вечный запрет — в отличие от файла-флага.
exec 9>"$LOCK_FILE"
flock -n 9 || die "другой деплой уже выполняется ($LOCK_FILE)"

git diff --quiet && git diff --cached --quiet \
  || die "в рабочей копии есть незакоммиченные изменения — сначала разберитесь с ними"

# Неотслеживаемые файлы — тот же класс опасности, что и правки: `git checkout`
# их НЕ удаляет и НЕ перезаписывает, поэтому файл, положенный в рабочую копию
# руками, переживёт любую выкладку и любой откат. `app/analytics.py.bak`,
# случайный `sitecustomize.py`, недоделанный шаблон — всё это молча продолжит
# участвовать в работе прода, а `deploy.sh <sha>` будет уверенно печатать, что
# в бою ровно этот коммит. Fail-closed: любые локальные изменения — отказ.
DIRTY="$(git status --porcelain 2>/dev/null || true)"
[ -z "$DIRTY" ] || die "в рабочей копии есть локальные изменения (в том числе неотслеживаемые файлы):
$DIRTY
   Уберите их: git clean -nd (посмотреть), git clean -fd (удалить). Игнорируемые
   файлы проверке не мешают — они перечислены в .gitignore осознанно."

echo "== 3/7 Проверяем целевой коммит =="
# Сеть уже была на шаге 2/7: `git fetch` там обязателен, чтобы узнать актуальный
# драйвер, и второй раз ходить незачем.
TARGET="${1:-origin/main}"
SHA="$(git rev-parse --verify "$TARGET^{commit}")" || die "не найден коммит: $TARGET"
CURRENT="$(git rev-parse --verify 'HEAD^{commit}')"
# Выкатывать можно только то, что прошло через main: случайный SHA из чужой
# ветки не должен оказаться в бою по опечатке.
git merge-base --is-ancestor "$SHA" origin/main \
  || die "коммит $SHA не принадлежит истории origin/main"
echo "сейчас: $CURRENT"
echo "цель:   $SHA"

# ЦЕЛЬ ОТКАТА (OPS-8). Прежний код считал целью отката текущий HEAD и записывал
# его в PREVIOUS_SHA всегда. При повторной выкладке ТОГО ЖЕ коммита — а она
# штатна: ею доигрывают выкладку, начатую старым драйвером, — это записывало
# цель отката равной выкладываемому релизу. Три последствия сразу: подсказка
# предлагала откат на самого себя, настоящая цель отката из записи исчезала, и
# уборка переставала её защищать, то есть дешёвый откат D-44 держался на том,
# что в квоте случайно было место.
#
# Правило простое и проверяемое: маркеры отката двигает только выкладка, которая
# действительно меняет коммит. Повторная выкладка того же SHA прежнюю запись
# читает и переиспользует, но не переписывает.
[ "$SHA" = "$CURRENT" ] && SAME_SHA=1
if [ "$SAME_SHA" = 1 ]; then
  RECORDED_SHA=""
  RECORDED_VENV=""
  [ -f "$PREVIOUS_FILE" ] \
    && RECORDED_SHA="$(tr -d '[:space:]' < "$PREVIOUS_FILE" 2>/dev/null || true)"
  [ -f "$PREVIOUS_VENV_FILE" ] \
    && RECORDED_VENV="$(tr -d '[:space:]' < "$PREVIOUS_VENV_FILE" 2>/dev/null || true)"
  if is_sha40 "$RECORDED_SHA" && [ "$RECORDED_SHA" != "$SHA" ]; then
    ROLLBACK_SHA="$RECORDED_SHA"
    case "$RECORDED_VENV" in /*) ROLLBACK_VENV="$RECORDED_VENV";; esac
  fi
  echo "повторная выкладка того же коммита — записанная цель отката сохраняется"
else
  ROLLBACK_SHA="$CURRENT"
fi

echo "== 4/7 Окружение целевого релиза =="
# ПОВТОРНАЯ ВЫКЛАДКА ТОГО ЖЕ SHA — ПРОВЕРКА, А НЕ ПЕРЕСБОРКА (OPS-8).
# Если код уже на целевом коммите, OBOROT_COMMIT уже равен ему, а живое
# окружение годно по метке и `python -m pip check`, то менять нечего: остаётся
# починить и проверить консольные обёртки и убедиться, что служба жива. Такой
# заход не собирает venv, не подменяет окружение, не снимает копию базы и не
# перезапускает службу — потому что каждое из этих действий стоит рисков, а
# менять им нечего. D-46 при этом не ослаблен, наоборот: окна «код новый,
# служба старая» на этом маршруте не возникает вовсе.
if [ "$SAME_SHA" = 1 ] \
   && release_venv_ok "$VENV" "$SHA" \
   && grep -qxF "OBOROT_COMMIT=$SHA" "$ENV_FILE"; then
  REPAIR_ONLY=1
fi
if [ "$REPAIR_ONLY" = 1 ]; then
  echo "   код, окружение и OBOROT_COMMIT уже соответствуют $SHA — пересобирать нечего"
else
  STAGING_VENV="$VENV_ROOT/.venv-staging.$$"
  prepare_release_venv "$SHA" "$STAGING_VENV" \
    || die "не удалось собрать окружение для $SHA (прод не тронут)"
fi

echo "== 5/7 Копия базы =="
STAMP="$(date +%Y%m%d-%H%M%S)"
if [ "$REPAIR_ONLY" = 1 ]; then
  # Копия перед выкладкой защищает от плохого релиза. Релиза здесь нет: код,
  # env и библиотеки остаются те же самые, база не может пострадать от того,
  # чего не произошло.
  echo "менять нечего — копия перед выкладкой не нужна"
elif [ -f "$DATA_DIR/oborot.db" ]; then
  BACKUP="$DATA_DIR/backups/oborot-$STAMP.db"
  sqlite3 "$DATA_DIR/oborot.db" ".backup '$BACKUP'"
  # Непроверенная копия — не копия. Дешёвый quick_check здесь уместнее полного
  # integrity_check: он ловит структурные повреждения, а выкладку не тормозит.
  sqlite3 "$BACKUP" 'PRAGMA quick_check;' | grep -qx 'ok' \
    || die "копия базы не прошла quick_check: $BACKUP"
  echo "копия: $BACKUP"
  # find/sort/awk вместо `ls | tail`: устойчиво к необычным именам файлов.
  find "$DATA_DIR/backups" -maxdepth 1 -type f -name 'oborot-*.db' \
    -printf '%T@ %p\n' | sort -rn | awk 'NR > 14 {sub(/^[^ ]+ /, ""); print}' \
    | xargs -r rm --
else
  echo "файла базы нет — первый запуск?"
fi

echo "== 6/7 Переключаемся на коммит =="
if [ "$REPAIR_ONLY" = 1 ]; then
  # Ничего не переключается: код уже на месте. Правится ровно первая строка
  # распознанных консольных обёрток — то единственное, что переезд каталога
  # ломает и что при этом чинится локально, без сети и без pip.
  echo "код уже на $SHA — чиню и проверяю окружение на месте"
  repair_console_shebangs "$VENV" \
    || die "не удалось починить консольные обёртки окружения в $VENV.
   Код, окружение и OBOROT_COMMIT не менялись, служба не перезапускалась."
  verify_live_venv "$SHA" \
    || die "окружение релиза $SHA не проходит проверку на финальном пути $VENV.
   Код, окружение и OBOROT_COMMIT не менялись, служба не перезапускалась."
else
# Обычная выкладка. Тело ветки сознательно оставлено на прежнем отступе: сдвиг
# на два пробела превратил бы точечную правку в переписанный целиком блок, и
# ревьюеру пришлось бы читать заново то, что не менялось. Проверить это дёшево:
# `git diff -w` показывает здесь ровно добавленные строки.

# С этой строки и до первого перезапуска сервиса любая ошибка означает откат:
# ловим и явные отказы шагов, и всё, что упадёт мимо них.
trap 'rollback_release "непредвиденная ошибка на строке $LINENO"' ERR
CODE_SWITCHED=1
git checkout --detach "$SHA" || rollback_release "не удалось переключиться на $SHA"
git --no-pager log -1 --format='%h %ad %s' --date=iso
set_commit_env "$SHA" || rollback_release "не удалось записать OBOROT_COMMIT"
ENV_SWITCHED=1
# VENV_SWAPPED выставляет сама функция — в тот момент, когда $VENV подменён.
# Снаружи это было бы поздно: между подменой и возвратом из функции есть ещё
# один шаг, и при его падении откат не знал бы, что окружение уже чужое.
swap_release_venv "$STAGING_VENV" || rollback_release "не удалось подменить окружение"
STAGING_VENV=""
# Починка консольных обёрток — ровно здесь и только здесь. Каталог уже стоит на
# финальном пути (раньше чинить нечего: путь ещё не тот), а служба ещё не
# перезапускалась — значит неудача лечится обычным откатом, а не аварией (D-46).
# Сети эта починка не требует, поэтому новых причин упасть у выкладки не
# появляется.
repair_console_shebangs "$VENV" \
  || rollback_release "не удалось починить консольные обёртки окружения в $VENV"
# Проверка окружения на финальном пути. Именно здесь ловится всё, что ломается
# переездом каталога, а не установкой пакетов.
verify_live_venv "$SHA" || rollback_release "окружение релиза не работает на финальном пути $VENV"
# Запись о цели отката — только когда цель настоящая, то есть когда коммит
# действительно сменился. Иначе прежняя запись остаётся как была (OPS-8).
if [ "$SAME_SHA" = 0 ]; then
  ROLLBACK_VENV="$PREV_VENV_PATH"
  printf '%s\n' "$PREV_VENV_PATH" > "$PREVIOUS_VENV_FILE"
fi
trap - ERR

fi

echo "== 7/7 Перезапуск и проверка =="
if [ "$REPAIR_ONLY" = 1 ]; then
  # Служба работает на том же коммите, том же окружении и том же env. Чинились
  # только консольные обёртки, которых работающий процесс не касается вовсе —
  # перезапускать его незачем, а лишний перезапуск прода это лишняя минута
  # недоступности и лишний риск на ровном месте.
  if service_ready_now; then
    echo "служба уже работает на $SHA — перезапуск не нужен"
    prune_release_venvs
    echo "прод = $SHA · $(rollback_hint)"
    exit 0
  fi
  echo "служба не отвечает — перезапускаю; код, env и библиотеки при этом не менялись" >&2
fi
# Точка невозврата: после перезапуска новый код мог тронуть базу, и решение об
# откате принимает человек (D-44, deploy/README.md «Почему откат ручной»).
RESTART_STARTED=1
if systemctl restart "$SERVICE" && wait_ready; then
  [ "$SAME_SHA" = 1 ] || printf '%s\n' "$CURRENT" > "$PREVIOUS_FILE"
  # Уборка старых окружений — только здесь, после успешного health-check. Раньше
  # она стояла ДО перезапуска, и это была ошибка: в окне «код переключён, сервис
  # ещё старый» откат обязателен (D-46), а уборка в этот момент могла унести
  # окружение, которым он и делается. Пока прод не поднялся на новом релизе,
  # лишний каталог на диске стоит дешевле отката без окружения.
  prune_release_venvs
  echo "прод = $SHA · $(rollback_hint)"
  exit 0
fi

# Автоматический откат сознательно НЕ делается — см. deploy/README.md,
# раздел «Почему откат ручной». Коротко: откат кода без отката данных
# безопасен только пока миграции аддитивные, и решать это должен человек,
# глядя на логи, а не скрипт в момент, когда уже что-то пошло не так.
echo "ПРИЛОЖЕНИЕ НЕ ПОДНЯЛОСЬ. Логи:" >&2
journalctl -u "$SERVICE" -n 60 --no-pager >&2 || true
echo >&2
if [ -n "$ROLLBACK_SHA" ] && [ "$ROLLBACK_SHA" != "$SHA" ]; then
  echo "ОТКАТ ОДНОЙ КОМАНДОЙ: bash deploy/deploy.sh $ROLLBACK_SHA" >&2
  if [ -n "$ROLLBACK_VENV" ] && [ -d "$ROLLBACK_VENV" ]; then
    echo "прежнее окружение цело: $ROLLBACK_VENV — откат обойдётся без сети" >&2
  fi
else
  # Молчать здесь нельзя, но и предлагать `deploy.sh` без аргумента — тоже:
  # это увело бы дежурного на вершину main вместо отката.
  echo "ОТКАТА ОДНОЙ КОМАНДОЙ НЕТ: прежний отличающийся релиз не записан." >&2
  echo "Выберите цель руками и сверьте её с журналом выпуска." >&2
fi
echo "копия базы перед этой выкладкой: ${BACKUP:-(копия не снималась)}" >&2
exit 1
