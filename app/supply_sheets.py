def _role_safe_failure(text, spreadsheet_id: str, sheet_names: list[str]) -> str:
    """Общий текст отказа: в нём нет ни одной строки, пришедшей от владельца.

    Замечание ревью PR #47 на HEAD `590b5c6`. Текст отказа собирается в двух
    десятках мест; требовать от каждого будущего места помнить про вторую роль
    — значит поставить приватность в зависимость от внимательности. Поэтому
    перед записью общий текст сверяется с ФАКТИЧЕСКИМИ строками этой попытки:
    идентификатором таблицы и именами обоих листов, как их прислал владелец.
    Совпало — текст заменяется на generic целиком, а не «затирается
    звёздочками»: частично затёртая строка всё ещё рассказывает свою длину и
    форму. Пустой результат тоже недопустим: пустая причина читается как «всё
    в порядке».

    ЧТО ЭТА ФУНКЦИЯ ДЕЛАЕТ СЕГОДНЯ, а чего не делает. Она осталась ровно на
    ОДНОМ пути — записи `last_error_public`, поля для старого кода после
    отката релиза. Сегодняшний читатель через неё не ходит вовсе: замечание
    ревью на HEAD `459f170` показало, что сверка persisted-текста с текущей
    попыткой в принципе не может доказать его актуальность — ни при откате
    (текст прошлой попытки строк текущей не содержит), ни при испорченном
    источнике попытки (сверять не с чем). Участнику теперь показывается
    константа из `PUBLIC_FAILURE_REASONS` по связанному коду
    (`_public_reason`), а не результат этой проверки.
    """
    if not isinstance(text, str) or not text.strip():
        return PUBLIC_FAILURE_FALLBACK
    owned = [value for value in ([spreadsheet_id] + list(sheet_names))
             if isinstance(value, str) and value.strip()]
    if any(value in text for value in owned):
        return PUBLIC_FAILURE_FALLBACK
    return text


def _attempt_identity(source) -> tuple[str, list[str]]:
    """Источник попытки в НОРМАЛИЗОВАННОМ виде: (идентификатор, имена листов).

    Одна функция и на записи, и на чтении — намеренно, по той же причине, по
    которой `ordered_carriers()` один на чтение и запись: две нормализации
    рано или поздно разойдутся, и связывание перестанет сходиться там, где
    данные целы. Всё, что не строка, здесь исчезает: испорченный источник
    попытки обязан давать не исключение, а недоказуемую связь.
    """
    if not isinstance(source, dict):
        return "", []
    raw_id = source.get("spreadsheet_id")
    names = source.get("sheet_names")
    return (
        raw_id if isinstance(raw_id, str) else "",
        [n for n in names if isinstance(n, str)] if isinstance(names, list) else [],
    )


def _public_binding(code: str, detailed: str, attempt_at, source) -> str:
    """Отпечаток, связывающий код причины с ЭТОЙ записанной неудачей.

    Зачем он нужен, если код и так из закрытого списка. Список гарантирует,
    что участник увидит НАШУ строку, а не чужую; он не гарантирует, что эта
    строка описывает СЕГОДНЯШНЮЮ неудачу. Живой сценарий из отчёта ревью:
    после отката старый писатель обновляет подробный текст и источник попытки,
    а незнакомое ему поле кода переносит из прежней записи как есть — и
    участник читает причину прошлой попытки как текущую. Отпечаток это
    закрывает конструктивно: он посчитан по тем самым полям, которые старый
    писатель перезаписывает, и после его правки перестаёт сходиться.

    Кодирование length-prefixed — тот же приём и по той же причине, что в
    `content_hash()`: имя листа может содержать любой символ, который мы бы
    взяли разделителем, и тогда две разные попытки дали бы один отпечаток.

    Это НЕ подпись и не защита от того, у кого есть право писать в базу: соли
    здесь нет, и посчитать отпечаток может кто угодно. Задача другая и она
    названа прямо — отличить запись, сделанную ЭТИМ кодом для ЭТОЙ неудачи, от
    пережитка отката, ручной правки и рассинхронизации полей.
    """
    spreadsheet_id, names = _attempt_identity(source)
    digest = hashlib.sha256()

    def part(chunk: bytes) -> None:
        digest.update(str(len(chunk)).encode("ascii"))
        digest.update(b"\x00")
        digest.update(chunk)

    part(b"supply-sheets-public-reason-1")
    part(code.encode("utf-8"))
    part(detailed.encode("utf-8"))
    part((attempt_at if isinstance(attempt_at, str) else "").encode("utf-8"))
    part(spreadsheet_id.encode("utf-8"))
    part(str(len(names)).encode("ascii"))
    for name in names:
        part(name.encode("utf-8"))
    return digest.hexdigest()


def _bounded_failure_text(text: str) -> str:
    """Текст отказа не длиннее потолка, по которому посчитан резерв записи.

    Обрезка — не косметика и не защита от «слишком длинных сообщений»: без
    неё `FAILURE_OVERLAY_BUDGET_BYTES` посчитать не из чего, и обещание «запись
    отказа помещается всегда» держалось бы на том, что все сегодняшние тексты
    случайно короткие. Сегодня она не срабатывает ни на одном живом отказе:
    самый длинный текст слоя вдвое короче потолка.

    Обрезанный текст помечается многоточием и никогда не пуст: пустая причина
    читалась бы как «всё в порядке». Считается в СИМВОЛАХ, как и потолок, —
    ровно то же измерение, из которого посчитан резерв.
    """
    if len(text) <= MAX_FAILURE_TEXT_CHARS:
        return text
    return text[:MAX_FAILURE_TEXT_CHARS - 1] + "…"


def _record_failure(db: Session, org_id: int, spreadsheet_id: str,
                    sheet_names: list[str], attempt_at: str,
                    exc: SourceError) -> None:
    """Отметить неудачу, НЕ тронув прежний успешный снимок.

    Меняются только поля ПОПЫТКИ: её время, её источник, подробный текст
    ошибки и то, по чему участник получит причину, — код из закрытого списка,
    отпечаток его связи с этой записью и общий текст для старого кода.
    `content_sha256`, `rows`, `fetched_at` и `last_success_at` остаются теми же
    — иначе неудачное обновление стирало бы единственное, что у пользователя
    есть, и «не получилось» превращалось бы в «данных больше нет».

    Причин у отказа две редакции, потому что читателей двое. Владелец ввёл
    ссылку и имена листов, ему их и чинить — он получает подробную причину с
    именем листа. Участник попытки не делал, и чужой ввод владельца ему не
    адресован — он получает нашу константу по коду.

    И ОТДЕЛЬНО — ПОЧЕМУ ЭТА ЗАПИСЬ МЕРЯЕТСЯ ДРУГИМ ПРЕДЕЛОМ. Она накладывается
    на уже принятый снимок и потому неизбежно делает его больше. Пока предел
    был один на всех, снимок, принятый у самой границы, переставал помещаться
    от одного лишь добавления причины: отсюда вылетал ВТОРОЙ отказ `too_big`,
    он подменял исходную причину в ответе, и метаданные попытки не сохранялись
    вовсе. Поэтому у служебной записи отказа свой предел — успешный плюс
    `FAILURE_OVERLAY_BUDGET_BYTES`, и оба текста заранее ограничены
    `_bounded_failure_text()`, чтобы этот резерв было из чего считать.

    Порядок здесь тоже значим: текст сначала ОБРЕЗАЕТСЯ, и только потом по нему
    считается отпечаток. Иначе на длинном отказе отпечаток перестал бы сходиться
    с сохранённым текстом, и участник молча получал бы generic вместо причины —
    ровно там, где длинный текст, то есть там, куда смотрят в последнюю очередь.
    """
    existing = get_envelope(db, org_id)
    envelope = dict(existing) if existing else _skeleton(spreadsheet_id, sheet_names)
    envelope["last_attempt_at"] = attempt_at
    envelope["last_attempt_source"] = {"spreadsheet_id": spreadsheet_id,
                                       "sheet_names": list(sheet_names)}
    envelope["last_error"] = _bounded_failure_text(str(exc))
    # Что видит участник — код из закрытого списка плюс отпечаток, которым
    # этот код связан с записанной здесь же неудачей. Свободного текста в этой
    # паре нет вовсе, поэтому «показать участнику чужую строку» больше нечем.
    code = getattr(exc, "code", "")
    code = code if code in PUBLIC_FAILURE_REASONS else ""
    envelope["last_error_public_code"] = code
    envelope["last_error_public_binding"] = _public_binding(
        code, envelope["last_error"], attempt_at,
        envelope["last_attempt_source"])
    # А это — для СТАРОГО кода после отката релиза: он про код и отпечаток не
    # знает и читает общий текст. Та же логика, по которой продолжает
    # писаться сохранённая сводка (`counts`): убрать поле значило бы не
    # упростить, а сломать откат. Сегодняшний читатель на него не опирается.
    envelope["last_error_public"] = _bounded_failure_text(_role_safe_failure(
        getattr(exc, "public", None), spreadsheet_id, sheet_names))
    # ЕДИНСТВЕННОЕ место, где предел записи больше предела успеха, и ровно на
    # вычисленный резерв. Запись по-прежнему одна транзакция одной колонки:
    # «отметили попытку, но не отметили причину» не бывает ни на каком шаге.
    _store(db, org_id, envelope,
           limit=MAX_ENVELOPE_BYTES + FAILURE_OVERLAY_BUDGET_BYTES)


# ── Сериализация обновлений одной организации ────────────────────────────────
#
# Замок процессный и этого достаточно ровно в тех границах, в которых сегодня
# живёт приложение: один воркер. Второй процесс он бы не удержал, и здесь это
# написано прямо, а не подразумевается.

_ORG_LOCKS: dict[int, threading.Lock] = {}
_LOCKS_GUARD = threading.Lock()


def _org_lock(org_id: int) -> threading.Lock:
    with _LOCKS_GUARD:
        lock = _ORG_LOCKS.get(org_id)
        if lock is None:
            lock = threading.Lock()
            _ORG_LOCKS[org_id] = lock
        return lock


# ── Обновление снимка ────────────────────────────────────────────────────────

def refresh(db: Session, org_id: int, spreadsheet_url: str, sheet_names,
            timeout: float = FETCH_TIMEOUT_SECONDS) -> dict:
    """Скачать оба листа, разобрать их и записать ОДИН последний снимок.

    Порядок здесь — не стиль, а требование: сначала проверка входа, затем
    носитель (нет носителя — 409 ДО единого сетевого вызова), затем оба листа
    целиком, и только потом единственная запись в базу. Частичного снимка
    («первый лист новый, второй прежний») не существует ни на одном шаге.
    """
    spreadsheet_id = parse_spreadsheet_url(spreadsheet_url)
    names = validate_sheet_names(sheet_names)

    if select_carrier(db, org_id) is None:
        raise NoCarrierError(
            "У организации нет основного подключения, в котором мог бы жить "
            "предпросмотр. Подключите МойСклад или демо-данные."
        )

    # Читаемость уже лежащего снимка проверяется ДО сети: снимок, который мы не
    # умеем прочитать, мы не имеем права и перезаписать, а узнать об этом после
    # двух GET значило бы сходить в чужую систему впустую. Проверяется тот
    # снимок, который ФАКТИЧЕСКИ найден (он может лежать не в каноническом
    # носителе), — и повреждённый останавливает обновление здесь же.
    get_envelope(db, org_id)

    with _org_lock(org_id):
        attempt_at = _now_iso()
        try:
            blobs = [fetch_sheet_csv(spreadsheet_id, name, timeout) for name in names]
            rows: list[dict] = []
            schema: dict[str, dict] = {}
            for name, blob in zip(names, blobs):
                parsed, sheet_schema = parse_sheet(name, decode_csv(name, blob))
                rows.extend(parsed)
                schema[name] = sheet_schema
        except SourceError as exc:
            _record_failure(db, org_id, spreadsheet_id, names, attempt_at, exc)
            raise

        digest = content_hash(spreadsheet_id, names, blobs)
        existing = get_envelope(db, org_id)
        if (existing and existing.get("content_sha256") == digest
                and existing.get("last_success_at")):
            # Тот же источник, те же байты, тот же парсер. Строки не
            # переписываются вовсе: честно обновляется только метаданные
            # попытки, и выдавать это за новый импорт нельзя.
            envelope = dict(existing)
            envelope["last_attempt_at"] = attempt_at
            envelope["last_attempt_source"] = {"spreadsheet_id": spreadsheet_id,
                                               "sheet_names": list(names)}
            envelope["last_error"] = ""
            envelope["last_error_public"] = ""
            envelope["last_error_public_code"] = ""
            envelope["last_error_public_binding"] = ""
            _store(db, org_id, envelope)
            return {
                "unchanged": True,
                "content_sha256": digest,
                "fetched_at": envelope.get("fetched_at"),
                "last_success_at": envelope.get("last_success_at"),
                # Та же сводка, что увидит GET: если сохранённая сделана
                # прежней версией разбора, здесь тоже пересчитанная — два
                # разных ответа про одни и те же строки были бы расхождением
                # интерфейса и расчёта.
                "counts": _counts_view(envelope.get("rows") or [],
                                       list(names)),
            }

        now = _now_iso()
        envelope = {
            "schema_version": ENVELOPE_SCHEMA_VERSION,
            "parser_version": PARSER_VERSION,
            "spreadsheet_id": spreadsheet_id,
            "sheet_names": list(names),
            "content_sha256": digest,
            "last_attempt_at": attempt_at,
            "last_success_at": now,
            "fetched_at": now,
            "last_error": "",
            "last_error_public": "",
            "last_error_public_code": "",
            "last_error_public_binding": "",
            "last_attempt_source": {"spreadsheet_id": spreadsheet_id,
                                    "sheet_names": list(names)},
            "schema": schema,
            "counts": build_counts(rows, names),
            "rows": rows,
        }
        try:
            # Размер проверяется ДО записи: снимок, который не помещается в
            # отведённый предел, не должен доехать до базы вовсе — прежний
            # остаётся на месте, а пользователь получает причину.
            _guard_envelope_size(envelope)
        except SourceError as exc:
            _record_failure(db, org_id, spreadsheet_id, names, attempt_at, exc)
            raise
        _store(db, org_id, envelope)
        return {
            "unchanged": False,
            "content_sha256": digest,
            "fetched_at": now,
            "last_success_at": now,
            "counts": envelope["counts"],
        }


# ── Непривязанная подсказка по каталогу ──────────────────────────────────────

def suggestion_from_candidates(candidates: list[str]) -> dict:
    """Ноль / один / несколько кандидатов — и ни одной сохранённой связи.

    Даже единственное точное совпадение остаётся КАНДИДАТОМ: связь позиции
    источника с карточкой каталога — продуктовое решение, а не вывод из
    совпадения строк. `product_id` наружу не отдаётся вовсе, чтобы клиент не
    смог случайно построить на подсказке привязку.
    """
    if not candidates:
        return {"status": "none", "count": 0, "candidates": [], "linked": False,
                "label": "Совпадений в каталоге нет"}
    if len(candidates) == 1:
        return {"status": "one", "count": 1, "candidates": list(candidates),
                "linked": False, "label": "Кандидат, не привязано"}
    return {"status": "many", "count": len(candidates),
            "candidates": list(candidates), "linked": False,
            "label": "Несколько кандидатов, не привязано"}


def name_candidates(db: Session, org_id: int, names: list[str]) -> dict[str, list[str]]:
    """Точное (посимвольное) совпадение имени с `base_name` каталога организации.

    Никакого fuzzy: ни регистронезависимости, ни расстояний, ни «похоже».
    Подсказка вычисляется в GET и никуда не сохраняется.

    ЧЕСТНАЯ ОГОВОРКА: сегодня ключ каталога — сам `base_name` (TECH_DEBT DATA-9),
    поэтому множество точных совпадений по имени вырождается в ноль или один,
    и исход «несколько» на живых данных недостижим. Ветка существует и
    проверяется на уровне `suggestion_from_candidates`, потому что закрытие
    DATA-9 сделает её достижимой; выдавать её за наблюдаемую сегодня — нельзя.
    """
    wanted = sorted({n for n in names if n})
    if not wanted:
        return {}
    rows = db.execute(
        select(Product.base_name).where(
            Product.org_id == org_id,
            Product.base_name.in_(wanted),
        ).distinct()
    ).scalars().all()
    found = set(rows)
    return {name: ([name] if name in found else []) for name in wanted}


# ── Чтение снимка ────────────────────────────────────────────────────────────

def filter_rows(rows: list[dict], sheet: str | None, queue: str) -> list[dict]:
    """Отбор строк для очереди. Воронка: все ⊇ требуют разбора ⊇ ошибки.

    Пустые строки-разделители остаются только в режиме «все»: в очереди
    разбора им делать нечего, а из общей таблицы убирать их нельзя — это
    физические строки чужого листа, и нумерация без них поедет.
    """
    out = [r for r in rows if not sheet or r.get("sheet_name") == sheet]
    if queue == "needs_review":
        out = [r for r in out if not r.get("is_blank") and _row_flags(r)[0]]
    elif queue == "invalid":
        out = [r for r in out if not r.get("is_blank") and _row_flags(r)[1]]
    return out


def _attempt_view(source) -> dict:
    """Последняя ПОПЫТКА как её показывают форме: ссылка и имена листов.

    Ссылка собирается сервером из сохранённого идентификатора — в браузер не
    уезжает ни одна строка, пришедшая от пользователя, даже та, которую он же
    и прислал. Идентификатор, не прошедший бы сегодняшнюю проверку, ссылкой не
    становится вовсе.
    """
    spreadsheet_id, names = _attempt_identity(source)
    return {
        "spreadsheet_id": spreadsheet_id,
        "spreadsheet_url": spreadsheet_link(spreadsheet_id) if spreadsheet_id else "",
        "sheet_names": names,
    }


def _public_reason(envelope: dict, detailed: str) -> str:
    """Причина отказа для участника. ВСЕГДА строка из нашего исходника.

    Замечание ревью PR #47 на HEAD `459f170`. Прежняя редакция отдавала
    участнику сохранённый в носителе свободный текст (`last_error_public`),
    если тот не содержал подстрок текущей попытки. Носитель — это то, что
    оставил кто-то другой, и у такой проверки было два промаха:

      * ОТКАТ. Старый писатель меняет `last_error` и `last_attempt_source`, но
        незнакомое ему поле общего текста переносит как есть. Сверка проходит
        (в тексте прошлой попытки нет строк текущей), и участник читает
        причину прошлой попытки как сегодняшнюю;
      * ИСПОРЧЕННЫЙ ИСТОЧНИК ПОПЫТКИ. Нет `last_attempt_source` или он не того
        вида — сверять не с чем, «совпадений не найдено», и произвольный текст
        уезжает участнику целиком.

    Общее у обоих: показывалась persisted-строка, актуальность которой ничем
    не доказана. Поэтому теперь не проверяется текст — текст вообще не
    берётся. Берётся КОД из закрытого списка `PUBLIC_FAILURE_REASONS`, и
    показывается наша константа по этому коду. Чтобы код не оказался
    пережитком чужой записи, он обязан сойтись отпечатком (`_public_binding`)
    с ФАКТИЧЕСКИМИ полями этой неудачи — подробным текстом, временем попытки и
    её источником. Не сошлось, нет кода, код неизвестен — generic.

    Fail closed здесь означает «беднее», а не «пусто»: причина участнику видна
    всегда, потому что пустое место читалось бы как «всё в порядке».
    """
    code = envelope.get("last_error_public_code")
    if not isinstance(code, str) or code not in PUBLIC_FAILURE_REASONS:
        return PUBLIC_FAILURE_FALLBACK
    binding = envelope.get("last_error_public_binding")
    if not isinstance(binding, str) or not binding:
        return PUBLIC_FAILURE_FALLBACK
    expected = _public_binding(code, detailed, envelope.get("last_attempt_at"),
                               envelope.get("last_attempt_source"))
    if binding != expected:
        return PUBLIC_FAILURE_FALLBACK
    return PUBLIC_FAILURE_REASONS[code]


def _error_view(envelope: dict, role: str) -> str:
    """Причина последнего отказа так, как её можно показать ЭТОЙ роли.

    Владельцу — подробный текст: имена листов и ссылку вводил он, чинить их
    ему, и без имени листа он не знает, какой из двух листов сломался.

    Участнику — константа из закрытого списка по сохранённому коду причины,
    и ни одной строки из носителя (`_public_reason`). Снимок, записанный кодом
    ДО этого разделения, откатом или рукой, кода не несёт либо не сходится
    отпечатком — участник получает generic.

    Пустым результат при непустой причине не бывает никогда: пустая причина
    читалась бы как «всё в порядке», а это неправда.
    """
    detailed = envelope.get("last_error") or ""
    if role == "owner":
        return detailed if isinstance(detailed, str) else ""
    if not (isinstance(detailed, str) and detailed):
        return ""
    return _public_reason(envelope, detailed)


def preview(db: Session, org_id: int, role: str, sheet: str | None = None,
            queue: str = "all", offset: int = 0, limit: int = 50) -> dict:
    """Страница снимка для GET. Только чтение, ни одной мутации."""
    if queue not in QUEUES:
        raise ValidationError("Неизвестный фильтр очереди.")
    try:
        offset = int(offset)
        limit = int(limit)
    except (TypeError, ValueError):
        raise ValidationError("offset и limit должны быть целыми числами.") from None
    if offset < 0:
        raise ValidationError("offset не может быть отрицательным.")
    if limit < 1 or limit > 200:
        raise ValidationError("limit должен быть от 1 до 200.")

    # Один проход по носителям: есть ли вообще где хранить и где снимок лежит
    # фактически. `read_envelope` не пишет ничего — GET остаётся строго
    # read-only, включая случай, когда снимок нашёлся не в каноническом
    # носителе: переносить его «заодно» здесь нельзя, перенос — это запись.
    carriers = ordered_carriers(db, org_id)
    envelope = read_envelope(db, org_id)[1] if carriers else None

    base = {
        "role": role,
        "can_refresh": role == "owner",
        "carrier_present": bool(carriers),
        "queue": queue,
        "sheet": sheet or "",
        "offset": offset,
        "limit": limit,
        "issue_labels": dict(ISSUE_LABELS),
        "invalid_issues": sorted(INVALID_ISSUES),
        "size_labels": list(SIZE_LABELS),
        # Подпись, которая обязана быть видна рядом с любыми числами этого
        # экрана. Она приходит с сервера, а не живёт только в вёрстке, чтобы
        # её нельзя было потерять правкой шаблона.
        "disclaimer": ("Предпросмотр источника — ещё не партия «Оборота» "
                       "и не учитывается в «Едет»."),
    }
    if not envelope:
        base.update({
            "configured": False,
            "spreadsheet_url": "", "spreadsheet_id": "", "sheet_names": [],
            "last_success_at": None, "last_attempt_at": None,
            "fetched_at": None, "last_error": "",
            "content_sha256": "", "parser_version": PARSER_VERSION,
            "schema_version": ENVELOPE_SCHEMA_VERSION,
            "parser_stale": False,
            "attempt": _attempt_view(None),
            "counts": build_counts([], []), "total": 0, "rows": [],
        })
        return base

    rows = envelope.get("rows") or []
    sheet_names = list(envelope.get("sheet_names") or [])
    if sheet and sheet not in sheet_names:
        raise ValidationError("Такого листа в предпросмотре нет.")

    selected = filter_rows(rows, sheet or None, queue)
    page = selected[offset:offset + limit]

    suggestions = name_candidates(db, org_id,
                                  [r.get("name") or "" for r in page])
    out_rows = []
    for row in page:
        item = dict(row)
        name = row.get("name") or ""
        item["labels"] = [ISSUE_LABELS.get(code, code) for code in row.get("issues", [])]
        item["needs_review"], item["invalid"] = _row_flags(row)
        item["suggestion"] = (suggestion_from_candidates(suggestions.get(name, []))
                              if name else suggestion_from_candidates([]))
        out_rows.append(item)

    spreadsheet_id = envelope.get("spreadsheet_id") or ""
    base.update({
        "configured": bool(spreadsheet_id),
        "spreadsheet_id": spreadsheet_id,
        # Ссылку на источник строит СЕРВЕР из сохранённого идентификатора —
        # в браузер не уезжает ни одна строка, пришедшая от пользователя.
        "spreadsheet_url": spreadsheet_link(spreadsheet_id) if spreadsheet_id else "",
        "sheet_names": sheet_names,
        "last_success_at": envelope.get("last_success_at"),
        "last_attempt_at": envelope.get("last_attempt_at"),
        "fetched_at": envelope.get("fetched_at"),
        # Причина отказа видна ОБЕИМ ролям: это состояние раздела, а не чужой
        # ввод. Но подробность у неё разная — см. `_error_view`.
        "last_error": _error_view(envelope, role),
        "content_sha256": envelope.get("content_sha256") or "",
        "parser_version": envelope.get("parser_version") or "",
        "schema_version": envelope.get("schema_version"),
        # Снимок, сделанный прежней версией разбора, читается — но выдавать
        # его за сегодняшнее прочтение нельзя: колонки тогда понимались иначе.
        # Лечится он сам, первым же обновлением (версия парсера входит в хеш).
        "parser_stale": bool(envelope.get("parser_version"))
                        and envelope.get("parser_version") != PARSER_VERSION,
        # Что человек вводил в прошлый раз. Нужно ровно для одного случая:
        # ПЕРВОЕ обновление не удалось, успешного снимка ещё нет, и без этого
        # человек увидел бы четырёхсекундный тост и пустую форму — то есть
        # вводил бы ссылку и два имени листов заново, не понимая, что пошло не
        # так. Это НЕ объявление источника настроенным: `configured` остаётся
        # false, пока нет ни одного удачного чтения.
        #
        # И это ТОЛЬКО владельцу — замечание ревью PR #47. Неудачная попытка
        # принадлежит тому, кто её сделал: ввести ссылку и имена листов может
        # один лишь владелец, форму восстанавливать нужно ему же, а участнику
        # это состояние не адресовано вовсе. Успешный снимок остаётся общим
        # (D-51: владелец и участник видят одно и то же), а адрес и листы
        # ПОПЫТКИ, которая ничем не закончилась, наружу роли, которая её не
        # делала, не уезжают.
        "attempt": (_attempt_view(envelope.get("last_attempt_source"))
                    if role == "owner" else _attempt_view(None)),
        "counts": _counts_view(rows, sheet_names),
        "total": len(selected),
        "rows": out_rows,
    })
    return base
