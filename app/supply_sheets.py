# это разные события. Отказ ничего нового не приносит — он объясняет уже
# принятое.
#
# ДВА ЧИСЛА, А НЕ ОДНО, И ЭТО НЕ ДУБЛИРОВАНИЕ. Потолок резерва НАЗНАЧЕН
# владельцем (27 525 байт; полный error-envelope — 1 076 101), и потому стоит
# литералом: одобрено было именно это число, а выводимое молча уехало бы
# вместе с любой правкой соседней константы. Рядом стоит ВЫЧИСЛЕННЫЙ худший
# случай, и он обязан в потолок помещаться — иначе модуль не импортируется.
# Так «ограниченный» остаётся свойством кода, а не обещанием описания, и
# одновременно остаётся решением владельца, а не следствием чьей-то правки.
#
# ОЦЕНКА ГРУБАЯ СВЕРХУ И ЛОКАЛЬНАЯ. За длиной свободного текста берётся худший
# случай экранирования в JSON (шесть байт на символ), хотя кириллица занимает
# два, а латиница один; за строкой, алфавит которой задан нашим же кодом
# (отпечаток, ключ причины, отметка времени, идентификатор таблицы), — её
# честная ASCII-длина. КАЖДОЕ слагаемое обязано быть границей само по себе, а
# не за счёт запаса в соседнем: замечание независимого ревью на HEAD
# `ae50ba0` — прежняя редакция заряжала члену объекта один байт разделителя
# вместо двух и была верна только в сумме. Сумма, которая держится на чужом
# запасе, перестаёт быть верной от первой же правки соседнего слагаемого.
#
# Почему считается ПОЛНЫЙ размер новых полей, а не прирост. Прежние значения
# тех же ключей занимают ноль байт или больше — значит, прирост не превосходит
# полного размера новых значений при любом прежнем содержимом, включая случай,
# когда ключа в снимке не было вовсе. Это не гипотетика: `_ENVELOPE_SHAPE`
# требует из шести полей только `last_error`, поэтому у снимка старой версии
# после отката недостающими могут оказаться ровно пять — и им нужен не только
# размер значения, но и ключ с разделителем.
#
# И отсюда же — почему повторные отказы не разгоняют размер: шесть полей
# ЗАМЕНЯЮТСЯ, а не дописываются, поэтому вторая неудача подряд даёт ровно ту
# же оценку, что и первая.

#: Худший случай JSON-экранирования одного символа: `"\u0000"` — шесть байт.
#: Больше не бывает: не-ASCII при `ensure_ascii=False` уезжает как UTF-8 (до
#: четырёх байт), а `"` и `\` — двумя.
_JSON_WORST_BYTES_PER_CHAR = 6

#: Длина отпечатка `_public_binding()` — шестнадцатеричный SHA-256.
_BINDING_CHARS = 64


def _json_text_bytes(max_chars: int) -> int:
    """Потолок байтов JSON-строки из `max_chars` ЛЮБЫХ символов, с кавычками."""
    return 2 + max_chars * _JSON_WORST_BYTES_PER_CHAR


def _json_ascii_bytes(max_chars: int) -> int:
    """То же для строки, алфавит которой задан НАШИМ кодом и заведомо ASCII.

    Экранирования в такой строке нет вовсе: ни кавычки, ни обратной косой,
    ни управляющего символа в шестнадцатеричном отпечатке, в ключе закрытого
    списка причин, в отметке времени `_now_iso()` и в идентификаторе таблицы
    (его алфавит задан `_SPREADSHEET_URL_RE`) взяться неоткуда. Это не
    оптимизация, а честность оценки: писать шестибайтовый потолок там, где символ
    физически не может быть не-ASCII, значило бы выдавать запас за расчёт.
    """
    return 2 + max_chars


def _json_member_bytes(key: str, value_bytes: int) -> int:
    """ВЕРХНЯЯ ГРАНИЦА байтов, которые добавляет один новый член объекта.

    Считается всё, что может появиться в сериализации вместе с ним:
    разделитель `", "` (2), ключ в кавычках (`len(key) + 2`; ключи здесь —
    ASCII-литералы этого модуля), `": "` (2) и само значение.

    Разделитель заряжается ВСЕГДА, в том числе первому члену объекта, которому
    он не нужен. Это сознательный пересчёт в большую сторону: граница обязана
    оставаться верной локально, сама по себе, а не за счёт запаса, спрятанного
    в соседнем слагаемом. Замечание независимого ревью на HEAD `ae50ba0`:
    прежняя редакция заряжала один байт вместо двух и была верна только в
    сумме — то есть обещала как свойство члена то, что свойством члена не
    является.
    """
    return 2 + len(key) + 2 + 2 + value_bytes


#: Источник попытки целиком: `{"sheet_names": [.., ..], "spreadsheet_id": …}`.
#: Два члена и две скобки; имена листов — пользовательский ввод, поэтому по
#: худшему экранированию, идентификатор — по ASCII-алфавиту своей регулярки.
_ATTEMPT_SOURCE_MAX_BYTES = (
    2
    + _json_member_bytes(
        "sheet_names",
        2 + SHEET_COUNT * (_json_text_bytes(MAX_SHEET_NAME_CHARS) + 2))
    + _json_member_bytes("spreadsheet_id",
                         _json_ascii_bytes(MAX_SPREADSHEET_ID_CHARS))
)

#: Худший случай записи ОДНОГО отказа поверх любого принятого снимка.
#:
#: Считается ПОЛНЫЙ размер шести новых членов, а не прирост: прежние значения
#: тех же ключей занимают ноль байт или больше, поэтому прирост не превосходит
#: этой суммы ни при каком прежнем содержимом — включая снимок старой версии
#: после отката, где пяти из шести ключей нет вовсе (обязателен по
#: `_ENVELOPE_SHAPE` только `last_error`).
_FAILURE_OVERLAY_WORST_BYTES = (
    _json_member_bytes("last_attempt_at",
                       _json_ascii_bytes(MAX_ATTEMPT_TIME_CHARS))
    + _json_member_bytes("last_attempt_source", _ATTEMPT_SOURCE_MAX_BYTES)
    + _json_member_bytes("last_error",
                         _json_text_bytes(MAX_FAILURE_TEXT_CHARS))
    + _json_member_bytes("last_error_public",
                         _json_text_bytes(MAX_FAILURE_TEXT_CHARS))
    + _json_member_bytes(
        "last_error_public_code",
        _json_ascii_bytes(max(len(code) for code in PUBLIC_FAILURE_REASONS)))
    + _json_member_bytes("last_error_public_binding",
                         _json_ascii_bytes(_BINDING_CHARS))
)

#: РЕШЕНИЕ ВЛАДЕЛЬЦА 01.09.2026 (DECISIONS D-52). Успешный снимок остаётся
#: строго в пределах 1 МиБ, а служебная запись отказа получает сверх него ровно
#: 27 525 байт и ни байтом больше: полный error-envelope — 1 076 101 байт.
#: Число здесь НАЗНАЧЕНО владельцем как потолок, а не выведено кодом, и потому
#: записано литералом: выводимое число молча уехало бы вместе с любой правкой
#: соседней константы, а одобрен был именно этот потолок.
FAILURE_OVERLAY_BUDGET_BYTES = 27_525

#: А это — доказательство, что потолок владельца достаточен, и оно обязано
#: держаться в самом коде, а не в описании PR. Поднимут потолок текста отказа
#: или длину имени листа так, что худший случай перестанет помещаться, — модуль
#: не импортируется вовсе, и об этом узнают на первом же прогоне, а не тогда,
#: когда пользователь потеряет причину отказа.
if _FAILURE_OVERLAY_WORST_BYTES > FAILURE_OVERLAY_BUDGET_BYTES:  # pragma: no cover
    raise RuntimeError(
        f"резерв под запись отказа ({FAILURE_OVERLAY_BUDGET_BYTES} байт, "
        f"решение владельца) меньше худшего случая "
        f"({_FAILURE_OVERLAY_WORST_BYTES} байт) — поднимать его нельзя без "
        f"нового решения владельца, границы метаданных отказа надо сузить"
    )


class SourceError(SupplySheetsError):
    """Источник не отдал того, что мы умеем читать (502).

    Один тип на сеть, HTTP-статус, HTML-страницу входа, битый CSV, дрейф
    заголовка и превышение лимитов — потому что для пользователя все они
    означают одно: снимок не обновлён, прежний остался на месте.

    У отказа ДВА текста, и это замечание ревью PR #47 на HEAD `590b5c6`.
    Подробный (`str(exc)`) называет физический лист чужой таблицы — имя листа
    ввёл владелец, ему же его и чинить, и без имени он не поймёт, какой из двух
    листов сломался. Но тот же текст уезжал в общий `last_error` и оттуда — в
    GET, который читает ЛЮБОЙ участник организации: чужой ввод владельца
    становился видимым роли, которая попытки не делала. Поэтому рядом живёт
    `public` — та же причина без единой строки, пришедшей от пользователя.

    `public` СЕГОДНЯ НЕ ПОКАЗЫВАЕТСЯ УЧАСТНИКУ: он пишется в носитель для
    старого кода после отката (`last_error_public`), а участник видит
    константу из `PUBLIC_FAILURE_REASONS` по коду `code`. Причина — замечание
    ревью на HEAD `459f170`: свободный текст из носителя ничем не связан с
    записанной неудачей, и доказать его актуальность нечем.

    `code` — ключ этого списка, и по умолчанию он ПУСТ. Пустой код неизвестен
    списку, а неизвестный код читается как generic: забытый на новом месте
    отказа код обедняет сообщение, но не может показать участнику неправду.
    Именно так и должно ломаться то, что охраняет приватность.
    """

    def __init__(self, message: str, public: str | None = None,
                 code: str = ""):
        super().__init__(message)
        #: Та же причина, но без ввода владельца. Никогда не пустая.
        self.public = public if public else message
        #: Ключ `PUBLIC_FAILURE_REASONS`. Неизвестный — значит generic.
        self.code = code if code in PUBLIC_FAILURE_REASONS else ""


# ── Транспорт: инъектируемый, чтобы живого Google не было в обязательном CI ──

@dataclass
class HttpResponse:
    """Ответ внешнего источника в том объёме, который нам нужен."""

    status: int
    headers: dict
    body: bytes
    url: str


def _httpx_get(method: str, url: str, timeout: float) -> HttpResponse:
    """Единственный сетевой вызов слоя: GET с bounded read и без редиректов.

    Редиректы выключены НАМЕРЕННО: их разбирает `_fetch_url` и проверяет хост
    у каждого перехода. Библиотечное `follow_redirects=True` увело бы нас на
    `accounts.google.com` молча — то есть ровно туда, куда нельзя.

    Чтение потоковое и ограниченное: `r.content` вычитал бы в память всё, что
    прислал источник, и лимит проверялся бы уже после того, как он потрачен.
    """
    import httpx

    if method != "GET":
        raise SourceError("этот слой умеет только GET", code="unavailable")

    chunks: list[bytes] = []
    total = 0
    with httpx.Client(follow_redirects=False, timeout=timeout) as client:
        try:
            with client.stream("GET", url, headers={"Accept": "text/csv"}) as resp:
                status = resp.status_code
                headers = dict(resp.headers)
                final_url = str(resp.url)
                if status == 200:
                    for chunk in resp.iter_bytes():
                        total += len(chunk)
                        if total > MAX_RESPONSE_BYTES:
                            raise SourceError(
                                f"ответ источника больше допустимых "
                                f"{MAX_RESPONSE_BYTES // 1024} КиБ",
                                code="too_big",
                            )
                        chunks.append(chunk)
        except SourceError:
            raise
        except httpx.TimeoutException:
            raise SourceError("источник не ответил за отведённое время",
                              code="unavailable") from None
        except httpx.HTTPError:
            raise SourceError("не удалось связаться с источником",
                              code="unavailable") from None
    return HttpResponse(status=status, headers=headers, body=b"".join(chunks),
                        url=final_url)


#: Точка инъекции. Тест подменяет транспорт и доказывает, что запросов ровно
#: два, метод только GET, хост только docs.google.com, а МойСклад не трогается.
_transport = None


def set_transport(fn) -> None:
    """Подменить транспорт (только для тестов). `None` — вернуть настоящий."""
    global _transport
    _transport = fn


def get_transport():
    return _transport or _httpx_get


# ── Валидация входа ──────────────────────────────────────────────────────────

def parse_spreadsheet_url(raw: str) -> str:
    """`spreadsheet_id` из канонической ссылки. Иначе — `ValidationError`.

    Возвращается ИДЕНТИФИКАТОР, а не URL: дальше запрос строит сервер. Это и
    есть граница, отделяющая «пользователь показал свою таблицу» от «клиент
    заставил сервер сходить по произвольному адресу».

    ТИП проверяется первым, и это замечание ревью PR #47, а не педантизм. Тело
    запроса — нетипизированный JSON-объект, и `{"spreadsheet_url": 123}` доезжал
    до `(raw or "").strip()`, где число даёт `AttributeError`: вместо
    обещанного 400 «поправьте ссылку» пользователь получал 500. Ошибка клиента
    обязана оставаться ошибкой клиента — управляемой, названной и без единого
    сетевого вызова. `None` считается пустым вводом (человек ничего не
    прислал), любой другой не-строке отвечаем прямо, что здесь ждут текст;
    `bool` в том числе — в Python он подкласс `int`, но строкой от этого не
    становится.
    """
    if raw is not None and not isinstance(raw, str):
        raise ValidationError(
            "Ссылка на таблицу должна быть текстом — пришло значение другого вида."
        )
    value = (raw or "").strip()
    if not value:
        raise ValidationError("Вставьте ссылку на таблицу Google Sheets.")
    if len(value) > 2048:
        raise ValidationError("Ссылка слишком длинная.")
    match = _SPREADSHEET_URL_RE.match(value)
    if not match:
        raise ValidationError(
            "Нужна обычная ссылка вида "
            "https://docs.google.com/spreadsheets/d/<идентификатор>/… — "
            "другие адреса этот раздел не открывает."
        )
    return match.group("id")


def _sheet_name_problem(raw) -> str:
    """Почему это НЕ годное имя листа. Пустая строка — значит годное.

    Один предикат на ДВЕ границы, и это не экономия строк. Имя листа приходит
    к нам двумя разными дорогами: от владельца в форме и из сохранённого
    снимка, который оставил кто-то другой (прежняя версия кода, откат релиза,
    чужая рука). Требование к самому имени у обеих дорог одно и то же, и если
    его записать дважды, две редакции однажды разойдутся — а разойдясь, дадут
    ровно то, против чего вся эта проверка: носитель, который читатель считает
    годным, а писатель негодным, или наоборот.

    А вот ТИП ОТКАЗА у двух границ разный, и поэтому предикат ничего не
    поднимает сам. Пользовательский ввод — это `ValidationError` (400): его
    прислал человек, ему и чинить. Сохранённый снимок — `CarrierConfigError`
    (409): его никто сейчас не присылал, и «ты прислал ерунду» было бы
    неправдой; чинится он обновлением, а не другим запросом. Смешать эти два
    исхода значило бы отвечать 400 на состояние базы.
    """
    if not isinstance(raw, str):
        return "Имя листа должно быть текстом."
    value = raw.strip()
    if not value:
        return "Имя листа не может быть пустым."
    if len(value) > MAX_SHEET_NAME_CHARS:
        return f"Имя листа длиннее {MAX_SHEET_NAME_CHARS} символов."
    if _CONTROL_CHARS_RE.search(value):
        return "В имени листа есть управляющие символы."
    return ""


def validate_sheet_names(names) -> list[str]:
    """Ровно два имени листов, в присланном порядке. Порядок значим.

    Первый лист — текущий, второй — следующий: так их видит владелец, и так
    они лягут в снимок. Менять порядок «для красоты» нельзя — сравнение
    снимков идёт по хешу, в который порядок входит.
    """
    if not isinstance(names, (list, tuple)):
        raise ValidationError("Имена листов должны прийти списком из двух значений.")
    if len(names) != SHEET_COUNT:
        raise ValidationError(
            f"Нужно ровно {SHEET_COUNT} листа: текущий и следующий."
        )
    out: list[str] = []
    for raw in names:
        problem = _sheet_name_problem(raw)
        if problem:
            raise ValidationError(problem)
        out.append(raw.strip())
    if out[0] == out[1]:
        raise ValidationError(
            "Текущий и следующий лист должны быть разными: иначе предпросмотр "
            "покажет один и тот же лист дважды."
        )
    return out


def build_csv_url(spreadsheet_id: str, sheet_name: str) -> str:
    """Endpoint CSV. Строит СЕРВЕР, целиком, из проверенных частей.

    `headers=0` обязателен: у этой таблицы ДВЕ физические строки заголовка, и
    любое «умное» распознавание заголовка на стороне Google съело бы одну из
    них вместе с позиционным контрактом размеров.
    """
    return (
        f"https://{GOOGLE_HOST}/spreadsheets/d/{spreadsheet_id}/gviz/tq"
        f"?tqx=out:csv&headers=0&sheet={quote(sheet_name, safe='')}"
    )


def spreadsheet_link(spreadsheet_id: str) -> str:
    """Безопасная ссылка «открыть исходник» — тоже собирается сервером."""
    return f"https://{GOOGLE_HOST}/spreadsheets/d/{spreadsheet_id}/edit"


def _require_google_url(url: str) -> None:
    """Схема https и хост РОВНО docs.google.com, без userinfo."""
    parsed = urlparse(url)
    if parsed.scheme != "https":
        raise SourceError("источник попытался увести запрос с https",
                          code="unavailable")
    if parsed.username or parsed.password:
        raise SourceError("в адресе источника есть учётные данные",
                          code="unavailable")
    if (parsed.hostname or "").lower() != GOOGLE_HOST:
        raise SourceError(
            f"источник попытался увести запрос на посторонний адрес "
            f"(ожидался {GOOGLE_HOST})",
            code="unavailable",
        )


# ── Отказ, у которого два адресата ───────────────────────────────────────────

def _sheet_error(sheet_name: str, detail: str, where: str = "",
                 code: str = "") -> SourceError:
    """Отказ по конкретному листу: владельцу с именем листа, остальным без него.

    Один конструктор на все такие отказы намеренно. Пока текст собирался на
    месте, единственным способом не забыть про вторую роль была аккуратность
    автора — а она масштабируется хуже, чем один helper. `detail` и `where`
    принадлежат НАМ (наш контракт, номер колонки, номер строки), и потому
    едут обеим ролям целиком; чужое здесь ровно одно — имя листа.
    """
    return SourceError(f"лист «{sheet_name}»{where}: {detail}",
                       f"лист источника{where}: {detail}", code=code)


# ── Загрузка одного листа ────────────────────────────────────────────────────

def _fetch_url(url: str, timeout: float) -> HttpResponse:
    """GET с ручной обработкой редиректов и проверкой хоста на каждом шаге."""
    _require_google_url(url)
    transport = get_transport()
    current = url
    hops = 0
    while True:
        resp = transport("GET", current, timeout)
        if resp.status in (301, 302, 303, 307, 308):
            hops += 1
            if hops > MAX_REDIRECTS:
                raise SourceError("источник переадресует запрос по кругу",
                                  code="unavailable")
            location = ""
            for key, value in (resp.headers or {}).items():
                if str(key).lower() == "location":
                    location = str(value)
                    break
            if not location:
                raise SourceError("источник ответил переадресацией без адреса",
                              code="unavailable")
            target = urljoin(current, location)
            _require_google_url(target)
            current = target
            continue
        return resp


def fetch_sheet_csv(spreadsheet_id: str, sheet_name: str,
                    timeout: float = FETCH_TIMEOUT_SECONDS) -> bytes:
    """Сырые байты CSV одного листа. Любая беда — `SourceError` без тела ответа."""
    resp = _fetch_url(build_csv_url(spreadsheet_id, sheet_name), timeout)

    if resp.status in (401, 403):
        raise _sheet_error(
            sheet_name,
            f"таблица не открыта на чтение по ссылке "
            f"(источник ответил {resp.status})", code="access")
    if resp.status == 404:
        raise _sheet_error(sheet_name, "таблица или лист не найдены (404)",
                           code="missing")
    if resp.status != 200:
        raise _sheet_error(sheet_name, f"источник ответил {resp.status}",
                           code="unavailable")

    content_type = ""
    for key, value in (resp.headers or {}).items():
        if str(key).lower() == "content-type":
            content_type = str(value).lower()
            break

    body = resp.body or b""
    if len(body) > MAX_RESPONSE_BYTES:
        raise _sheet_error(
            sheet_name,
            f"ответ больше допустимых {MAX_RESPONSE_BYTES // 1024} КиБ",
            code="too_big")
    if not body.strip():
        raise _sheet_error(sheet_name, "источник вернул пустой ответ",
                           code="unavailable")

    head = body[:512].lstrip(b"\xef\xbb\xbf").lstrip().lower()
    if content_type.startswith("text/html") or head.startswith((b"<!doctype", b"<html")):
        raise _sheet_error(
            sheet_name,
            "источник вернул страницу входа, а не CSV — похоже, таблица "
            "закрыта и её просят открыть после авторизации", code="access")
    return body


# ── Контракт заголовка: маленький, явный, без догадок ────────────────────────
#
# ЭТИ ПОЗИЦИИ — НАБЛЮДЕНИЕ, А НЕ ДОГАДКА, и однажды они уже были неверны.
# Первая версия слоя (отвергнутый ревью HEAD `a25e163`) задала весь каркас НА
# ОДНУ КОЛОНКУ ЛЕВЕЕ: ждала «Наименование» в колонке 2, размерную горку с 9,
# итог в 14. Синтетическая фикстура повторяла ту же ошибку — и потому весь
# набор был зелёным, а оба живых листа падали ДО первой строки данных.
# Урок записан здесь, а не только в журнале: фикстура, сочинённая по той же
# памяти, что и код, ничего не проверяет. Ниже — форма, снятая read-only с
# точных публичных байтов обоих листов 31.08.2026; живой CSV в репозиторий не
# кладётся (там PII), в тестах — две синтетические формы этого каркаса.
#
# Наблюдены ДВЕ законные формы строки 2, и обе поддержаны намеренно:
