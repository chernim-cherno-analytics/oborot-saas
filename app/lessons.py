def pick_sample(turnover: dict) -> dict | None:
    """«Живой» пример для тура: бестселлер, который вот-вот кончится.

    Вход — результат app.analytics.build_turnover (не лезем в таблицы сами:
    там уже применены исключения, архив, пороги организации и покрытие
    истории). Берём только группу 'rank' (у 'low_data' оборачиваемость —
    арифметический шум, учить на ней нельзя), из неё лучший присутствующий
    класс, а внутри класса — позицию с наименьшим запасом в днях. Это самый
    показательный случай: вещь зарабатывает больше всех и скоро кончится.

    None — если учить пока не на чем (организация синкается первую минуту,
    продаж и остатков ещё нет). Сезонные значения (sea) при неполной истории
    приходят как null — их здесь не трогаем вовсе.
    """
    cands = []
    for it in turnover.get("items") or []:
        if it.get("group") != "rank" or it.get("archived") or it.get("hidden"):
            continue
        rate = float(it.get("rate") or 0)      # темп продаж, шт/день
        stock = int(it.get("cs") or 0)         # остаток, шт
        if rate <= 0 or stock <= 0:
            continue
        cands.append({
            "name": it.get("base_name") or "",
            "category": it.get("category") or "",
            "rate": int(it.get("turnover") or 0),   # оборачиваемость, ₽/день
            "stock": stock,
            "supply_days": max(0, round(stock / rate)),
            "cls": it.get("cls") or "weak",
        })
    if not cands:
        return None
    best_cls = next((c for c in _CLS_ORDER if any(x["cls"] == c for x in cands)), None)
    pool = [x for x in cands if x["cls"] == best_cls]
    # Наименьший запас; при равном запасе — та, что зарабатывает больше.
    pool.sort(key=lambda x: (x["supply_days"], -x["rate"], x["name"]))
    return pool[0]
