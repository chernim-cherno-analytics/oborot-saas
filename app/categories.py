_CYRILLIC_RE = re.compile("[а-яё]", re.IGNORECASE)


def category_by_name(name: str) -> str | None:
    """Категория по ключевым словам в названии товара (русские имена)."""
    nl = (name or "").lower()
    for cat, keywords in _NAME_CATEGORIES:
        if any(k in nl for k in keywords):
            return cat
    return None


def ru_category(raw: str, name: str = "") -> str:
    """Категория для отображения: кириллица как есть, латиница — перевод/по имени."""
    cat = (raw or "").strip()
    if cat and _CYRILLIC_RE.search(cat):
        return cat
    if cat:
        translated = CAT_TRANSLATIONS.get(cat.lower())
        if translated:
            return translated
    by_name = category_by_name(name)
    if by_name:
        return by_name
    return cat or "Прочее"
