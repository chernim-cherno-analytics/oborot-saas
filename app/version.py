# -*- coding: utf-8 -*-
"""Версия домена и версия сборки — для записей решений.

Зачем две разные величины.

`BUILD_COMMIT` — что именно исполнялось. Ставится при деплое переменной
окружения `OBOROT_COMMIT`; меняется от любой правки, включая CSS. По нему
можно поднять точный код, который дал конкретную рекомендацию.

`DOMAIN_VERSION` — меняется ли ОТВЕТ. Поднимается вручную, когда меняется
смысл расчёта: формула потребности, темпа, минимальной партии, календаря
платежей, отбора кандидатов. Без неё нельзя отличить «система стала считать
иначе» от «данные изменились»: два плана, посчитанные в разные дни, различались
бы, и причина была бы неизвестна.

Правило: правишь то, что меняет число в плане, — поднимаешь DOMAIN_VERSION
и дописываешь строку в историю ниже.

История:
  1 — 22.08.2026, первая зафиксированная версия. Волны must-have → дыры →
      база → углубление; минимальная партия как пол; сезонность как индекс
      к активному темпу; накладные расходы; кратность упаковки; бюджет
      «сейчас» = первый транш календаря.
"""
import os

DOMAIN_VERSION = 1

BUILD_COMMIT = (os.environ.get("OBOROT_COMMIT") or "").strip()[:40]


def algo_version() -> dict:
    """Подпись алгоритма для записи решения."""
    return {"domain": DOMAIN_VERSION, "commit": BUILD_COMMIT or None}
